// Whitespace in the original display labels is trimmed explicitly; wire values stay literal.
func GTPv2MessageName(typ uint64) string {
	if label, ok := gtpv2MessageNames[typ]; ok {
		return strings.TrimSpace(label)
	}
	return fmt.Sprintf("Unselected message type %d", typ)
}
func GTPv2IEName(typ uint64) string {
	if label, ok := gtpv2IENames[typ]; ok {
		return strings.TrimSpace(label)
	}
	return fmt.Sprintf("Unselected IE type %d", typ)
}
