func TestRADIUSAccessRequestFromCapture(t *testing.T) {
	eth := parseEthernet(t, radiusAccessRequestFrame)
	r := mustChild(t, eth, "IP", "UDP", "RADIUS")
	require.Equal(t, uint64(1), uintVal(t, r.Child("Code")))
	require.Equal(t, uint64(0x8d), uintVal(t, r.Child("Identifier")))
	require.Equal(t, uint64(1), uintVal(t, mustChild(t, r, "Attributes", "Type")))
	require.Equal(t, []byte("Admin"), bytesVal(t, mustChild(t, r, "Attributes", "Value")))
}

func TestTLSClientHelloFromCapture(t *testing.T) {
	eth := parseEthernet(t, tlsClientHelloFrame)
	rec := mustChild(t, eth, "IP", "TCP", "TLS", "Record Layer")
	require.Equal(t, uint64(22), uintVal(t, rec.Child("ContentType")))
	suites := bytesVal(t, mustChild(t, rec, "TLSClientHello", "ClientHello", "Cipher Suites"))
	require.True(t, len(suites) >= 4)
	require.Equal(t, []byte{0xc0, 0x14}, suites[:2])
}

func TestSNMPRFC1157GetRequestOID(t *testing.T) {
	raw, err := codec.DecodeHex("302602010004067075626c6963a019020101020100020100300e300c06082b060102010101000500")
	require.NoError(t, err)
	snmp := parseRule(t, raw, "application-layer.snmp", "SNMP")
	require.Equal(t, []byte{0x2b, 0x06, 0x01, 0x02, 0x01, 0x01, 0x01, 0x00}, bytesVal(t, mustChild(t, snmp, "PDU Body", "Variable Bindings", "Bindings", "OID")))
	eth := parseEthernet(t, ipv4UDPFrame(t, 40000, 161, gopacket.Payload(raw)))
	require.Equal(t, []byte("public"), bytesVal(t, mustChild(t, eth, "IP", "UDP", "SNMP", "Community")))
}

func TestLDAPAnonymousBindSample(t *testing.T) {
	// LDAP simple anonymous bind (RFC 4511 BindRequest, empty name + simple auth).
	bind := []byte{0x30, 0x0c, 0x02, 0x01, 0x01, 0x60, 0x07, 0x02, 0x01, 0x03, 0x04, 0x00, 0x80, 0x00}
	n := parseRule(t, bind, "application-layer.ldap", "LDAPMessage")
	require.Equal(t, []byte{3}, bytesVal(t, mustChild(t, n, "Body", "ProtocolOp", "BindRequest", "Version")))
	require.Equal(t, uint64(0x80), uintVal(t, mustChild(t, n, "Body", "ProtocolOp", "BindRequest", "Auth Tag")))
}

func TestRDPTPKTFromProtocolImplCapture(t *testing.T) {
	raw, err := codec.DecodeHex("030000221de000004e5500c108302d304142434430c208302d305a59585731c0010a")
	require.NoError(t, err)
	n := parseRule(t, raw, "application-layer.msrdp", "TPKT")
	require.Equal(t, uint64(3), uintVal(t, n.Child("Version")))
	require.Equal(t, raw[4:], bytesVal(t, n.Child("TPDU")))
}
