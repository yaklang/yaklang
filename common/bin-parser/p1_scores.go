func ResolveP1Scorecard(name string) (ProtocolScorecard, bool) {
	byName := make(map[string]ProtocolScorecard, len(P1Scorecards))
	for _, s := range P1Scorecards {
		byName[s.Name] = s
	}
	s, ok := byName[name]
	if !ok {
		return ProtocolScorecard{}, false
	}
	if s.AliasOf == "" {
		return s, true
	}
	base, ok := resolveAliasCard(s.AliasOf, byName, P0Scorecards)
	if !ok {
		return ProtocolScorecard{}, false
	}
	base.Name = name
	base.AliasOf = s.AliasOf
	return base, true
}

func resolveAliasCard(of string, p1 map[string]ProtocolScorecard, p0 []ProtocolScorecard) (ProtocolScorecard, bool) {
	if s, ok := p1[of]; ok {
		if s.AliasOf == "" {
			return s, true
		}
		return resolveAliasCard(s.AliasOf, p1, p0)
	}
	for _, s := range p0 {
		if s.Name == of {
			if s.AliasOf == "" {
				return s, true
			}
			return resolveAliasCard(s.AliasOf, p1, p0)
		}
	}
	return ProtocolScorecard{}, false
}
