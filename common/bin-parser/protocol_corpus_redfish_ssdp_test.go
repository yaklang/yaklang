func redfishSSDPTestAddHeader(wire, header string) string {
	return strings.TrimSuffix(wire, "\r\n") + header + "\r\n\r\n"
}

func TestProtocolCorpusRedfishSSDPSupportedVariations(t *testing.T) {
	fixtures := redfishSSDPTestFixtures()
	query, response, alive := fixtures[0].wire, fixtures[1].wire, fixtures[2].wire
	cases := []string{
		strings.Replace(query, "MX: 2", "MX: 60", 1), // The recommended <=5 is not a SHALL.
		strings.Replace(query, "HOST:", "hOsT:", 1),
		strings.Replace(query, "239.255.255.250:1900", "239.255.255.250", 1),
		strings.Replace(query, "239.255.255.250:1900", "[ff02::c]:1900", 1),
		strings.Replace(query, "239.255.255.250:1900", "[FF05::C]", 1),
		strings.Replace(query, "239.255.255.250:1900", "[ff02:0:0:0:0:0:0:c]:01900", 1),
		strings.Replace(alive, "max-age=1800", "max-age=0", 1), // UDA notification recommendation only.
		strings.Replace(response, "max-age=1800", "opaque=\"a,b\", MAX-AGE = 4294967295", 1),
		redfishSSDPTestAddHeader(query, "CONTENT-LENGTH: 000"),
		redfishSSDPTestAddHeader(response, "LOCATION: http://example.test/description.xml?name=a%20b"),
		redfishSSDPTestAddHeader(query, "x.example.test:\tvalue\t"),
		redfishSSDPTestAddHeader(query, "x.example.test: \x80\xff"),
	}
	for index, wire := range cases {
		t.Run(fmt.Sprint(index), func(t *testing.T) {
			node := protocolCorpusRequireBoundedRuleParse(t, []byte(wire), redfishSSDPCorpusRule, "RedfishSSDP")
			redfishSSDPTestFields(t, redfishSSDPTestMessage(t, node), wire, 0)
		})
	}
}

