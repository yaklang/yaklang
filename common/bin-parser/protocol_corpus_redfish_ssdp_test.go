func TestProtocolCorpusRedfishSSDPBoundariesAndGeneration(t *testing.T) {
	wire := []byte(redfishSSDPTestFixtures()[0].wire)
	for _, entry := range []string{"RedfishSSDP", "RedfishSSDPCarrier"} {
		_, err := parser.ParseBinary(bytes.NewReader(wire), redfishSSDPCorpusRule, entry)
		require.ErrorContains(t, err, "explicit")
		_, err = parser.GenerateBinary(map[string]any{"Method": "M-SEARCH"}, redfishSSDPCorpusRule, entry)
		require.ErrorContains(t, err, "explicit")
		_, err = parser.ParseBinary(newProtocolCorpusBoundedReader(nil), redfishSSDPCorpusRule, entry)
		require.Error(t, err)
		for extra := uint64(1); extra < 8; extra++ {
			root, err := base.ParseRule("application-layer/redfish_ssdp.yaml")
			require.NoError(t, err)
			root.Cfg.SetItem(base.CfgLength, uint64(len(wire))*8+extra)
			reader := bytes.NewReader(append(bytes.Clone(wire), 0))
			err = root.ParseSubNode(base.NewBitReader(reader), entry)
			require.ErrorContains(t, err, "explicit byte boundary")
			require.Equal(t, len(wire)+1, reader.Len(), "reject before reads")
		}
	}
	root, err := base.ParseRule("application-layer/redfish_ssdp.yaml")
	require.NoError(t, err)
	root.Cfg.SetItem(base.CfgLength, uint64(16385)*8)
	reader := bytes.NewReader([]byte{0x55})
	err = root.ParseSubNode(base.NewBitReader(reader), "RedfishSSDP")
	require.ErrorContains(t, err, "16384-byte parser profile")
	require.Equal(t, 1, reader.Len())
}

func TestProtocolCorpusRedfishSSDPResourceProfiles(t *testing.T) {
	query := redfishSSDPTestFixtures()[0].wire
	// Construct exact limits using independent complete extension header lines.
	maxBytes := query
	for len(maxBytes) < 16384 {
		length := 16384 - len(maxBytes)
		if length > 1024 {
			length = 1024
		}
		require.GreaterOrEqual(t, length, 5)
		maxBytes = redfishSSDPTestAddHeader(maxBytes, "X: "+strings.Repeat("v", length-5))
	}
	require.Len(t, maxBytes, 16384)
	maxCount := query
	for index := 0; index < 60; index++ {
		maxCount = redfishSSDPTestAddHeader(maxCount, "X: v")
	}
	maxName := redfishSSDPTestAddHeader(query, strings.Repeat("X", 64)+": v")
	maxHeader := redfishSSDPTestAddHeader(query, "X: "+strings.Repeat("v", 1019))
	for name, wire := range map[string]string{"message-bytes": maxBytes, "header-count": maxCount, "header-name": maxName, "header-bytes": maxHeader} {
		t.Run(name, func(t *testing.T) {
			node := protocolCorpusRequireBoundedRuleParse(t, []byte(wire), redfishSSDPCorpusRule, "RedfishSSDP")
			redfishSSDPTestFields(t, redfishSSDPTestMessage(t, node), wire, 0)
			count := 0
			var walk func(*base.Node)
			walk = func(n *base.Node) {
				count++
				for _, child := range n.Children {
					walk(child)
				}
			}
			walk(node)
			require.Less(t, count, 225, "tree grows with bounded headers, not individual bytes")
		})
	}
	for name, wire := range map[string]string{
		"message-bytes": maxBytes + "x",
		"header-count":  redfishSSDPTestAddHeader(maxCount, "X: v"),
		"header-name":   redfishSSDPTestAddHeader(query, strings.Repeat("X", 65)+": v"),
		"header-bytes":  redfishSSDPTestAddHeader(query, "X: "+strings.Repeat("v", 1020)),
	} {
		t.Run("over-"+name, func(t *testing.T) {
			_, err := parser.ParseBinary(newProtocolCorpusBoundedReader([]byte(wire)), redfishSSDPCorpusRule, "RedfishSSDP")
			require.Error(t, err)
			redfishSSDPTestRaw(t, []byte(wire))
		})
	}
}

func TestProtocolCorpusRedfishSSDPParallelIsolation(t *testing.T) {
	for index := 0; index < 24; index++ {
		index := index
		t.Run(fmt.Sprint(index), func(t *testing.T) {
			t.Parallel()
			fixture := redfishSSDPTestFixtures()[index%6]
			wire := fixture.wire
			if index%4 == 0 {
				wire = strings.ReplaceAll(wire, "redfish-rest", "redfish")
				redfishSSDPTestRaw(t, []byte(wire))
				return
			}
			entry := "RedfishSSDP"
			if index%2 == 0 {
				entry = "RedfishSSDPCarrier"
			}
			node := protocolCorpusRequireBoundedRuleParseWithConfig(t, []byte(wire), redfishSSDPCorpusRule, entry, map[string]any{"redfish-test-marker": index})
			message := redfishSSDPTestMessage(t, node)
			require.Equal(t, index, message.Ctx.GetItem("redfish-test-marker"))
			redfishSSDPTestFields(t, message, wire, 0)
			require.Equal(t, []byte(wire), NodeToBytes(node))
		})
	}
}
