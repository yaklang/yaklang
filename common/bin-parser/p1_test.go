func ipv4ProtoFrame(t *testing.T, proto layers.IPProtocol, payload []byte) []byte {
	t.Helper()
	eth := &layers.Ethernet{
		SrcMAC:       []byte{0x00, 0x11, 0x22, 0x33, 0x44, 0x55},
		DstMAC:       []byte{0x00, 0xaa, 0xbb, 0xcc, 0xdd, 0xee},
		EthernetType: layers.EthernetTypeIPv4,
	}
	ip := &layers.IPv4{
		Version:  4,
		TTL:      64,
		Protocol: proto,
		SrcIP:    []byte{10, 0, 0, 1},
		DstIP:    []byte{10, 0, 0, 2},
	}
	return serializeLayers(t, eth, ip, gopacket.Payload(payload))
}

func ethernet8023(dst, src, payload []byte) []byte {
	buf := make([]byte, 14+len(payload))
	copy(buf[0:6], dst)
	copy(buf[6:12], src)
	binary.BigEndian.PutUint16(buf[12:14], uint16(len(payload)))
	copy(buf[14:], payload)
	return buf
}

