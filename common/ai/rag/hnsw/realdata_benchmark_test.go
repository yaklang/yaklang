package hnsw

import (
	"bufio"
	"encoding/binary"
	"fmt"
	"io"
	"os"
	"runtime"
	"sort"
	"strconv"
	"testing"
	"time"
)

const realDataMagic = "YAKHNSW1"

type realVectorData struct {
	base    [][]float32
	queries [][]float32
}

func loadRealVectorData(path string) (*realVectorData, error) {
	file, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer file.Close()
	reader := bufio.NewReaderSize(file, 1024*1024)
	magic := make([]byte, len(realDataMagic))
	if _, err := io.ReadFull(reader, magic); err != nil {
		return nil, err
	}
	if string(magic) != realDataMagic {
		return nil, fmt.Errorf("invalid real-data magic %q", magic)
	}
	var header [3]uint32
	if err := binary.Read(reader, binary.LittleEndian, &header); err != nil {
		return nil, err
	}
	dims, baseCount, queryCount := int(header[0]), int(header[1]), int(header[2])
	if dims != 1024 || baseCount == 0 || queryCount == 0 {
		return nil, fmt.Errorf("invalid real-data header: dims=%d base=%d queries=%d", dims, baseCount, queryCount)
	}
	vectors := make([][]float32, baseCount+queryCount)
	for i := range vectors {
		vectors[i] = make([]float32, dims)
		if err := binary.Read(reader, binary.LittleEndian, vectors[i]); err != nil {
			return nil, fmt.Errorf("read vector %d: %w", i, err)
		}
	}
	return &realVectorData{base: vectors[:baseCount], queries: vectors[baseCount:]}, nil
}

func realDataEnvInt(name string, fallback int) int {
	if value, err := strconv.Atoi(os.Getenv(name)); err == nil && value > 0 {
		return value
	}
	return fallback
}

func realDataNodes(vectors [][]float32) []InputNode[int] {
	nodes := make([]InputNode[int], len(vectors))
	for i := range vectors {
		nodes[i] = MakeInputNode(i, vectors[i])
	}
	return nodes
}

func realDataExactTopK(nodes []InputNode[int], queries [][]float32, k int) []map[int]struct{} {
	exact := make([]map[int]struct{}, len(queries))
	for i := range queries {
		exact[i] = benchmarkExactTopK(nodes, queries[i], k)
	}
	return exact
}

func buildRealDataGraph(nodes []InputNode[int], m, efConstruction int) *Graph[int] {
	graph := NewGraph[int](
		WithDeterministicRng[int](42),
		WithM[int](m),
		WithEfConstruction[int](efConstruction),
	)
	graph.Add(nodes...)
	return graph
}

func TestHNSWRealData1024Benchmark(t *testing.T) {
	path := os.Getenv("YAK_HNSW_REAL_DATA")
	if path == "" {
		t.Skip("set YAK_HNSW_REAL_DATA to a file generated by cmd/hnsw-realdata")
	}
	data, err := loadRealVectorData(path)
	if err != nil {
		t.Fatal(err)
	}
	nodes := realDataNodes(data.base)
	const k = 10
	exact := realDataExactTopK(nodes, data.queries, k)
	m := realDataEnvInt("YAK_HNSW_M", 16)
	efConstruction := realDataEnvInt("YAK_HNSW_EF_CONSTRUCTION", 200)

	runtime.GC()
	var before, after runtime.MemStats
	runtime.ReadMemStats(&before)
	buildStarted := time.Now()
	graph := buildRealDataGraph(nodes, m, efConstruction)
	buildElapsed := time.Since(buildStarted)
	runtime.GC()
	runtime.ReadMemStats(&after)
	if graph.Len() != len(nodes) {
		t.Fatalf("built %d nodes, want %d", graph.Len(), len(nodes))
	}
	graphHeap := int64(after.HeapAlloc) - int64(before.HeapAlloc)
	t.Logf("REAL1024 n=%d queries=%d m=%d efConstruction=%d build=%s graphHeap=%.1fMiB buildAlloc=%.1fMiB",
		len(nodes), len(data.queries), m, efConstruction, buildElapsed,
		float64(graphHeap)/(1024*1024), float64(after.TotalAlloc-before.TotalAlloc)/(1024*1024))

	for _, efSearch := range []int{20, 32, 64, 128, 256} {
		graph.EfSearch = efSearch
		latencies := make([]time.Duration, 0, len(data.queries)*3)
		matches := 0
		started := time.Now()
		for repeat := 0; repeat < 3; repeat++ {
			for queryIndex, query := range data.queries {
				queryStarted := time.Now()
				results := graph.SearchWithDistance(query, k)
				latencies = append(latencies, time.Since(queryStarted))
				for _, result := range results {
					if _, ok := exact[queryIndex][result.Key]; ok {
						matches++
					}
				}
			}
		}
		elapsed := time.Since(started)
		sort.Slice(latencies, func(i, j int) bool { return latencies[i] < latencies[j] })
		recall := float64(matches) / float64(len(latencies)*k)
		qps := float64(len(latencies)) / elapsed.Seconds()
		t.Logf("REAL1024 efSearch=%d qps=%.0f p50=%s p95=%s recall@10=%.4f",
			efSearch, qps, latencies[len(latencies)/2], latencies[len(latencies)*95/100], recall)
	}
}

func BenchmarkHNSWRealData1024Search(b *testing.B) {
	path := os.Getenv("YAK_HNSW_REAL_DATA")
	if path == "" {
		b.Skip("set YAK_HNSW_REAL_DATA to a file generated by cmd/hnsw-realdata")
	}
	data, err := loadRealVectorData(path)
	if err != nil {
		b.Fatal(err)
	}
	nodes := realDataNodes(data.base)
	graph := buildRealDataGraph(
		nodes,
		realDataEnvInt("YAK_HNSW_M", 16),
		realDataEnvInt("YAK_HNSW_EF_CONSTRUCTION", 200),
	)
	graph.EfSearch = realDataEnvInt("YAK_HNSW_EF_SEARCH", 64)
	const k = 10
	var exact []map[int]struct{}
	if os.Getenv("YAK_HNSW_SKIP_EXACT") == "" {
		exact = realDataExactTopK(nodes, data.queries, k)
	}
	matches := 0
	b.ReportAllocs()
	b.ResetTimer()
	for i := 0; i < b.N; i++ {
		queryIndex := i % len(data.queries)
		benchmarkSearchSink = graph.SearchWithDistance(data.queries[queryIndex], k)
		if exact != nil {
			for _, result := range benchmarkSearchSink {
				if _, ok := exact[queryIndex][result.Key]; ok {
					matches++
				}
			}
		}
	}
	b.StopTimer()
	if exact != nil {
		b.ReportMetric(float64(matches)/float64(b.N*k), "recall@10")
	}
}
