package pcaputil

import (
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"testing"
	"time"

	"github.com/stretchr/testify/require"
)

func TestDLMSHDLCSNUploadIdleAndUntrackedResource(t *testing.T) {
	raw := finsReadBatch(t, "dlms-hdlc-sn-upload", "DLMS_HDLC_SN_UPLOAD_TEST_ROOT", "carrier-controls.json")
	require.Equal(t, "04509cdda9c58f0caff919e8b8413cc591df71261e48ad30055af4a80d07c391", fmt.Sprintf("%x", sha256.Sum256(raw)))
	var controls struct{ Cases []hdlcOpCase }
	require.NoError(t, json.Unmarshal(raw, &controls))
	require.Len(t, controls.Cases, 6)
	controls.Cases = controls.Cases[3:]
	for _, original := range controls.Cases {
		for _, deferred := range []bool{false, true} {
			t.Run(fmt.Sprintf("%s/deferred%t", original.Name, deferred), func(t *testing.T) {
				// Reparse per configuration so expected maps are never shared or generated by IUT.
				var all struct{ Cases []hdlcOpCase }
				require.NoError(t, json.Unmarshal(raw, &all))
				var c hdlcOpCase
				for _, v := range all.Cases {
					if v.Name == original.Name {
						c = v
					}
				}
				b := DefaultParserBudget()
				if len(c.Steps) == 2 {
					b.MaxFrameBytes = 64
					b.MaxMessageBytes = 64
				}
				s, err := NewProtocolSessionWithOptions(b, WithSessionTransport("udp"), WithSessionPorts(41000, 4059))
				require.NoError(t, err)
				defer s.Close("cleanup")
				s.(*captureSession).f.a.config.Deferred = deferred
				ids := make([]uint64, len(c.Steps))
				var snapshots, saved []*ProtocolEvent
				var flow uint64
				seen := map[uint64]bool{}
				for i, st := range c.Steps {
					wire := wrapperWire(t, st.Wire)
					require.Equal(t, st.SHA, fmt.Sprintf("%x", sha256.Sum256(wire)))
					out := s.Feed(st.Direction, time.Unix(st.At, 0), wire)
					clear(wire)
					require.Equal(t, len(wire), out.Consumed)
					require.False(t, out.NeedMore)
					if st.Error == "" {
						require.Nil(t, out.Err)
					} else {
						rocTypedError(t, st.Error, out.Err)
					}
					require.Len(t, out.Events, 1)
					e := out.Events[0]
					require.NotZero(t, e.ID)
					require.False(t, seen[e.ID])
					seen[e.ID] = true
					ids[i] = e.ID
					st = hdlcSNBlockBindStep(t, st, ids)
					c.Steps[i] = st
					require.Equal(t, CaptureDomain{}, e.Domain)
					ends := []string{"192.0.2.1:41000", "192.0.2.2:4059"}
					require.Equal(t, ends[st.Direction], e.Source)
					require.Equal(t, ends[1-st.Direction], e.Destination)
					if len(c.Steps) == 2 {
						require.Zero(t, e.FlowID)
					} else {
						require.NotZero(t, e.FlowID)
						if flow == 0 {
							flow = e.FlowID
						}
						require.Equal(t, flow, e.FlowID)
					}
					hdlcSNReadQueries(t, e, st)
					if st.Error != "" {
						snReadQueryError(t, e, st.Error)
						require.Nil(t, e.Session)
					} else {
						hdlcOpEqual(t, st.Session, e.Session)
						hdlcSNReadTypes(t, e.Session)
					}
					snapshots = append(snapshots, actionSnapshot(e))
					saved = append(saved, e)
					actionPoison(e)
					hdlcSNReadQueries(t, e, st)
				}
				hdlcOpCheck(t, c, snapshots, "udp", false, deferred)
				require.Empty(t, s.Close("test-close"))
				require.Empty(t, s.Close("repeat"))
				require.Zero(t, s.Stats().BufferedBytes)
				require.Zero(t, s.Stats().Incomplete)
				if len(c.Steps) == 2 {
					require.EqualValues(t, 65, s.Stats().LimitedBytes)
				} else {
					require.Zero(t, s.Stats().LimitedBytes)
				}
				require.LessOrEqual(t, s.Stats().PeakBufferedBytes, int64(b.MaxBufferedBytes))
				for i, e := range saved {
					hdlcSNReadQueries(t, e, c.Steps[i])
				}
			})
		}
	}
}
