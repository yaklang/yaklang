// Wrapper v1 transports selected complete unciphered LN Get/Action observations. wPorts
// are application addresses, separate from TCP/UDP ports. Observed pairing is
// not evidence of an authenticated or negotiated application association.
// Fixed overhead covers native, session and structured map projections. Wire
// strings and nested scalar fields are charged separately by complete frame size.
const wrapperProjectionBytes int64 = 4096

func wrapperError(k ProtocolErrorKind, why string) error {
	return protocolError(k, "DLMS Wrapper %s", why)
}
func wrapperFrameSize(w []byte, limit int) (int, error) {
	if len(w) < 8 {
		return 0, nil
	}
	n := 8 + int(binary.BigEndian.Uint16(w[6:8]))
	if n > limit {
		return 0, wrapperError(ErrResourceExceeded, "announced frame exceeds byte budget")
	}
	if len(w) < n {
		return 0, nil
	}
	return n, nil
}

type wrapperMessage struct {
	fields                 map[string]any
	source, destination    uint16
	invoke, flags, choice  byte
	command                byte
	count                  int
	request, confirmed     bool
	blockNumber            uint32
	setBlock, blockFirst   bool
	setParameterNodes      int
	blockData              []byte
	lastBlock, blockError  bool
	gbt                    bool
	gbtControl             byte
	gbtNumber, gbtAck      uint16
	acse, acseAccepted     bool
	acseRelease, acseAbort bool
	acseInfo               bool
	acseLowAuthentication  bool
	acseConformance        uint32
	acseMaxPDU             uint16
}

func decodeDLMSWrapper(w []byte, limit int) (*wrapperMessage, error) {
	return decodeDLMSWrapperBudget(w, limit, DefaultParserBudget().MaxRecursionDepth)
}

func decodeDLMSWrapperBudget(w []byte, limit, depth int) (*wrapperMessage, error) {
	bad := func(s string) (*wrapperMessage, error) { return nil, wrapperError(ErrMalformedMessage, s) }
	unsupported := func(s string) (*wrapperMessage, error) { return nil, wrapperError(ErrUnsupportedFeature, s) }
	if len(w) < 8 {
		return bad("Wrapper header truncated")
	}
	v, src, dst, n := binary.BigEndian.Uint16(w), binary.BigEndian.Uint16(w[2:]), binary.BigEndian.Uint16(w[4:]), int(binary.BigEndian.Uint16(w[6:]))
	if len(w) != 8+n {
		return bad("Wrapper declared payload length differs from complete frame")
	}
	if v != 1 {
		return unsupported("Wrapper version1 only")
	}
	p := w[8:]
	if len(p) == 0 {
		return unsupported("empty WPDU has no selected Get APDU")
	}
	if p[0] >= 0x60 && p[0] <= 0x64 {
		return decodeWrapperACSE(w, limit)
	}
	if p[0] == 0xe0 {
		return decodeWrapperGBT(w, limit)
	}
	if p[0] == 0xc1 || p[0] == 0xc5 {
		return decodeWrapperSet(w, limit, depth)
	}
	if p[0] == 0xc3 || p[0] == 0xc7 {
		return decodeWrapperAction(w, limit, depth)
	}
	if p[0] != 0xc0 && p[0] != 0xc4 {
		return unsupported("APDU outside unciphered LN Get")
	}
	if len(p) < 3 {
		return bad("Get service header truncated")
	}
	if p[1] != 1 && p[1] != 2 && p[1] != 3 {
		return unsupported("Get service choice outside selected1/2/3")
	}
	if p[2]&0x30 != 0 {
		return unsupported("flag pattern not generated by fixed reference")
	}
	f := map[string]any{"wrapper_version": v, "source_wport": src, "destination_wport": dst, "payload_length": n, "wrapper_header_hex": hex.EncodeToString(w[:8]), "apdu_hex": hex.EncodeToString(p), "association_observed": false, "authentication_verified": false, "object_model_verified": false, "command": p[0], "service_choice": p[1], "invoke_id_and_priority": p[2], "invoke_id": p[2] & 15, "high_priority": p[2]&128 != 0, "confirmed_service": p[2]&64 != 0, "unused_flag_bits_raw": p[2] & 0x30}
	m := &wrapperMessage{fields: f, source: src, destination: dst, invoke: p[2] & 15, flags: p[2], command: p[0], request: p[0] == 0xc0, confirmed: p[2]&64 != 0, choice: p[1], count: 1}
	if m.choice == 2 {
		if err := decodeWrapperBlock(m, p, limit); err != nil {
			return nil, err
		}
		return m, nil
	}
	if m.choice == 3 {
		if err := decodeWrapperList(m, p, limit, depth); err != nil {
			return nil, err
		}
		return m, nil
	}
	if m.request {
		if len(p) < 13 {
			return bad("Get-normal descriptor truncated")
		}
		if p[12] != 0 && p[12] != 1 {
			return unsupported("selected optional access selection0/1")
		}
		if p[12] == 0 && len(p) != 13 {
			return bad("Get-normal descriptor has trailing bytes")
		}
		if int8(p[11]) <= 0 {
			return unsupported("positive signed8 attribute profile")
		}
		f["kind"], f["class_id"], f["logical_name_hex"], f["logical_name"], f["attribute_id"], f["selective_access"] = "GetRequestNormal", binary.BigEndian.Uint16(p[3:5]), hex.EncodeToString(p[5:11]), fmt.Sprintf("%d.%d.%d.%d.%d.%d", p[5], p[6], p[7], p[8], p[9], p[10]), int8(p[11]), p[12] == 1
		if p[12] == 1 {
			// Observe selector and one complete bounded Data parameter. Meaning and
			// permissions depend on the COSEM object/association, not this envelope.
			c := wrapperListCursor{wire: p, at: 13, maxDepth: depth}
			selector, err := c.take(1)
			if err != nil {
				return nil, err
			}
			parameter, err := c.data(limit, 0)
			if err != nil {
				return nil, err
			}
			if c.at != len(p) {
				return bad("Get-normal access parameters have trailing bytes")
			}
			f["access_selection_raw"], f["access_selector"], f["access_parameters"], f["selector_semantics_verified"] = p[12], selector[0], parameter, false
		}
	} else {
		if len(p) < 5 {
			return bad("Get-normal result truncated")
		}
		f["kind"] = "GetResponseNormal"
		switch p[3] {
		case 0:
			var data map[string]any
			var err error
			if p[4] == 1 || p[4] == 2 || p[4] == 19 {
				c := wrapperListCursor{wire: p, at: 4, maxDepth: depth}
				data, err = c.data(limit, 0)
				if err == nil && c.at != len(p) {
					err = wrapperError(ErrMalformedMessage, "Get-normal Data has trailing bytes")
				}
			} else if wrapperExtendedScalarTag(p[4]) {
				c := wrapperListCursor{wire: p, at: 4}
				data, err = c.scalar(limit)
				if err == nil && c.at != len(p) {
					err = wrapperError(ErrMalformedMessage, "Get-normal Data has trailing bytes")
				}
			} else {
				// Preserve the existing scalar/octet representation and budget.
				data, err = wrapperScalar(p[4:], limit)
			}
			if err != nil {
				return nil, err
			}
			f["result_choice"], f["data"] = "data", data
		case 1:
			if len(p) != 5 {
				return bad("data-access-result trailing or missing bytes")
			}
			switch p[4] {
			case 0, 1, 2, 3, 4, 9, 11, 12, 13, 14, 15, 16, 17, 18, 19, 250:
			default:
				return unsupported("data-access-result not in pinned ErrorCode enumeration")
			}
			f["result_choice"], f["data_access_result"], f["operation_success"] = "data-access-result", p[4], p[4] == 0
		default:
			return unsupported("Get result discriminator outside selected reference encoding0/1")
		}
	}
	return m, nil
}
func wrapperScalar(w []byte, limit int) (map[string]any, error) {
	bad := func(s string) (map[string]any, error) { return nil, wrapperError(ErrMalformedMessage, s) }
	if len(w) == 0 {
		return bad("A-XDR Data missing")
	}
	tag, v := w[0], w[1:]
	out := map[string]any{"type": tag, "raw_hex": hex.EncodeToString(w)}
	// Reuse the static size switch instead of rebuilding a map for every Data
	// node. Extended scalar support is selected by the bounded cursor; this path preserves legacy scalar/octet fields.
	if n := wrapperScalarSize(tag); n >= 0 && tag != 23 && tag != 24 && tag != 25 && tag != 26 && tag != 27 {
		if len(v) != n {
			return bad("fixed A-XDR scalar size mismatch")
		}
		switch tag {
		case 0:
			out["value"] = nil
		case 3:
			out["value"], out["boolean_raw"] = v[0] != 0, v[0]
		default:
			var x uint64
			for _, b := range v {
				x = x<<8 | uint64(b)
			}
			if tag == 5 || tag == 15 || tag == 16 || tag == 20 {
				signed := int64(x)
				if n < 8 && v[0]&128 != 0 {
					signed -= int64(uint64(1) << (8 * n))
				}
				if signed <= -(1<<53) || signed >= (1<<53) {
					out["value"] = strconv.FormatInt(signed, 10)
				} else {
					out["value"] = signed
				}
			} else if x >= 1<<53 {
				out["value"] = strconv.FormatUint(x, 10)
			} else {
				out["value"] = x
			}
		}
		return out, nil
	}
	if tag != 9 {
		return nil, wrapperError(ErrUnsupportedFeature, "Data type outside bounded scalar/octet-string profile")
	}
	if len(v) == 0 {
		return bad("octet-string length missing")
	}
	count, at := uint64(v[0]), 1
	if v[0]&128 != 0 {
		k := int(v[0] & 127)
		if k != 1 && k != 2 && k != 4 {
			return nil, wrapperError(ErrUnsupportedFeature, "A-XDR count width outside pinned getObjectCount widths1/2/4")
		}
		if len(v) < 1+k {
			return bad("octet-string count truncated")
		}
		count = 0
		for _, b := range v[1 : 1+k] {
			count = count<<8 | uint64(b)
		}
		at += k
	}
	if count != uint64(len(v)-at) {
		return bad("octet-string length differs from complete value")
	}
	if count > uint64(limit) {
		return nil, wrapperError(ErrResourceExceeded, "octet-string exceeds value-byte/collection budget")
	}
	out["length"], out["length_encoding_hex"], out["value_hex"] = count, hex.EncodeToString(v[:at]), hex.EncodeToString(v[at:])
	return out, nil
}
func wrapperPortStart(w []byte, ports [2]uint16) bool {
	return len(w) > 0 && w[0] == 0 && (ports[0] == 4059 || ports[1] == 4059)
}
func probeDLMSWrapper(w []byte, limit int) ProbeResult {
	if len(w) < 2 || w[0] != 0 || w[1] != 1 {
		return ProbeResult{Verdict: ProbeReject}
	}
	n, err := wrapperFrameSize(w, limit)
	if err != nil {
		return ProbeResult{Verdict: ProbeReject}
	}
	if n == 0 {
		// The version prefix 0001 is also a valid Modbus transaction ID.
		// Once the APDU tag is available, retain only the selected Get prefix;
		// an unrelated incomplete envelope must reach the other probes.
		if !wrapperIncompletePrefix(w, limit) {
			return ProbeResult{Verdict: ProbeReject}
		}
		return probeNeed("dlms-wrapper", wrapperProbeVersion(w), len(w), max(8, len(w)+1))
	}
	if _, err := decodeDLMSWrapper(w[:n], 4096); err != nil {
		return ProbeResult{Verdict: ProbeReject}
	}
	return probeAccept("dlms-wrapper", wrapperProbeVersion(w), 98)
}

type wrapperToken struct {
	dir                 int
	source, destination uint16
	invoke              byte
}
type wrapperPending struct {
	id                    uint64
	flags, choice         byte
	command               byte
	count                 int
	pending, ambiguous    bool
	idleRetired           bool
	blockNumber           uint32
	lastSetBlock          bool
	setParameterNodes     int
	blockData             []byte
	blockActive, awaiting bool
	replyID               uint64
	blocks                int
}
type binDLMSWrapper struct {
	seen         map[wrapperToken]*wrapperPending
	associations map[wrapperAssociationKey]*wrapperAssociation
	gbt          map[wrapperGBTKey]*wrapperGBTTransfer
	blocked      bool
}

func (s *binDLMSWrapper) storage() int64 {
	n := 512 + 256*int64(len(s.seen)) + 256*int64(len(s.associations))
	for _, p := range s.seen {
		n += int64(len(p.blockData))
	}
	for _, p := range s.gbt {
		n += 512 + int64(cap(p.data)) + 128*int64(len(p.blocks))
	}
	return n
}
func (s *binDLMSWrapper) outstanding() int {
	n := 0
	for _, p := range s.associations {
		if p.pending || p.releasePending {
			n++
		}
	}
	for _, p := range s.seen {
		if p.pending {
			n++
		}
	}
	for _, p := range s.gbt {
		if p.active {
			n++
		}
	}
	return n
}
func (s *binDLMSWrapper) invalidate() {
	for _, p := range s.associations {
		p.pending = false
		p.ambiguous = true
		p.releasePending = false
		p.releaseAmbiguous = true
	}
	for _, p := range s.gbt {
		p.data = nil
		p.active = false
		p.ambiguous = true
	}
	for _, p := range s.seen {
		p.pending = false
		p.ambiguous = true
		p.retireBlocks()
	}
	s.blocked = true
}
func (f *binFlow) consumeWrapper(dir int, w []byte, e *ProtocolEvent) error {
	return f.consumeWrapperReserved(dir, w, e, 0)
}

// A reconstructed APDU shares a live outer GBT projection. Its reservation
// must not temporarily release that outer graph's credits to other flows.
func (f *binFlow) consumeWrapperReserved(dir int, w []byte, e *ProtocolEvent, floor int64) error {
	s := f.wrapper
	if s == nil {
		s = &binDLMSWrapper{}
		f.wrapper = s
	}
	// Reserve the complete field/projection graph and any new association slot
	// before allocating maps, raw hex strings or committing request identity.
	target := s.storage() + wrapperProjection(w, len(w)) + 256
	if wrapperIsACSE(w) && w[8] == 0x64 {
		target += 256
	} // Abort may retain both endpoint directions.
	if wrapperIsBlock(w) || wrapperIsSetBlock(w) {
		target += wrapperBlockBytes
	}
	target = max(target, floor)
	if err := f.reserveSession(target); err != nil {
		s.invalidate()
		var pe *ProtocolError
		if errors.As(err, &pe) {
			return pe
		}
		return err
	}
	depth := 2
	if wrapperUsesDataGraph(w) || wrapperIsGBT(w) {
		depth = 4
	}
	if f.a.budget.MaxRecursionDepth < depth {
		s.invalidate()
		return wrapperError(ErrResourceExceeded, "field depth exceeds recursion budget")
	}
	m, err := decodeDLMSWrapperBudget(w, f.a.budget.MaxCollectionElements, f.a.budget.MaxRecursionDepth)
	if err != nil {
		s.invalidate()
		return err
	}
	assoc := "unmatched-response"
	if s.blocked {
		assoc = "ambiguous-conversation"
	} else if m.acse {
		assoc, err = f.consumeWrapperACSE(s, m, dir, e)
		if err != nil {
			s.invalidate()
			return err
		}
	} else if s.wrapperEndpointClosed(dir, m.source, m.destination, m.request) {
		assoc = "retired-association-context"
	} else if m.gbt {
		assoc, err = f.consumeWrapperGBT(s, m, dir, e, w)
		if err != nil {
			s.invalidate()
			return err
		}
	} else if m.setBlock {
		assoc, err = f.consumeWrapperSetBlock(s, m, dir, e)
		if err != nil {
			return err
		}
	} else if m.choice == 2 {
		assoc, err = f.consumeWrapperBlock(s, m, dir, e, w)
		if err != nil {
			return err
		}
	} else if m.request {
		key := wrapperToken{dir, m.source, m.destination, m.invoke}
		if !m.confirmed {
			assoc = "unconfirmed-observation"
		} else if old := s.seen[key]; old != nil {
			old.ambiguousBlocks()
			assoc = old.ambiguousAssociation()
		} else if len(s.seen) >= f.a.budget.MaxCollectionElements {
			s.invalidate()
			return wrapperError(ErrResourceExceeded, "retained invoke context exceeds collection budget")
		} else {
			if s.seen == nil {
				s.seen = make(map[wrapperToken]*wrapperPending)
			}
			s.seen[key] = &wrapperPending{id: e.ID, command: m.command, flags: m.flags, choice: m.choice, count: m.count, pending: true}
			e.TransactionID = e.ID
			assoc = "observed-request"
		}
	} else {
		key := wrapperToken{1 - dir, m.destination, m.source, m.invoke}
		p := s.seen[key]
		if p != nil && p.ambiguous {
			assoc = p.ambiguousAssociation()
		} else if p != nil && p.pending && p.flags == m.flags && p.command != wrapperRequestCommand(m.command) {
			p.ambiguousBlocks()
			assoc = "ambiguous-service"
		} else if p != nil && p.pending && p.flags == m.flags && (p.command == 0xc1 && m.command == 0xc5 || p.command == 0xc3 && m.command == 0xc7) && p.choice != m.choice {
			p.ambiguousBlocks()
			assoc = "ambiguous-service"
		} else if p != nil && p.pending && p.flags == m.flags && (p.command == 0xc1 && m.command == 0xc5 && p.choice == 4 && m.choice == 4 || p.command == 0xc3 && m.command == 0xc7 && p.choice == 3 && m.choice == 3) && p.count != m.count {
			p.ambiguousBlocks()
			assoc = "ambiguous-result-count"
		} else if p != nil && p.pending && p.blockActive && p.flags == m.flags && (m.choice == 1 || m.choice == 3) {
			p.ambiguousBlocks()
			assoc = "ambiguous-block-transfer"
		} else if p != nil && p.pending && !p.blockActive && p.flags == m.flags && p.choice == m.choice && p.count == m.count {
			p.pending = false
			e.ResponseTo, e.TransactionID = p.id, p.id
			assoc = "observed-response"
		}
	}
	e.semanticFields = cloneSession(m.fields)
	e.Session = cloneSession(m.fields)
	e.Session["Association"], e.Session["Outstanding"] = assoc, s.outstanding()
	// Queries own the accepted wire fields and the observed invoke context.
	// Reuse private nested wire values; only this small root/context is new.
	e.semanticSession = make(map[string]any, len(e.Session))
	for k, v := range e.semanticFields {
		e.semanticSession[k] = v
	}
	e.semanticSession["Association"], e.semanticSession["Outstanding"] = assoc, s.outstanding()
	if m.acseRelease || m.acseAbort {
		retained := max(s.storage()+wrapperProjection(w, len(w)), floor)
		if retained < f.sessionBytes {
			f.a.buffered.Add(retained - f.sessionBytes)
			f.sessionBytes = retained
		}
	}
	return nil
}

const wrapperIdleTTL = 30 * time.Second

// Shared ingress may refuse before parsing or retaining an endpoint key. Only
// inspect the fixed Wrapper/service header here; this hint is not an accepted
// descriptor, Data value, association or authenticated peer generation.
func wrapperUDPRefusalHint(w []byte) bool {
	if wrapperIsACSE(w) {
		return wrapperACSERefusalHint(w)
	}
	if wrapperIsGBT(w) {
		return wrapperGBTRefusalHint(w)
	}
	if wrapperIsSetList(w) || wrapperIsActionList(w) {
		return len(w) >= 11 && int(binary.BigEndian.Uint16(w[6:8])) == len(w)-8 && w[10]&0x30 == 0
	}
	if wrapperIsAction(w) || wrapperIsSet(w) {
		return len(w) >= 11 && int(binary.BigEndian.Uint16(w[6:8])) == len(w)-8 && (w[9] == 1 || wrapperIsSetBlock(w)) && w[10]&0x30 == 0
	}
	return len(w) >= 11 && w[0] == 0 && w[1] == 1 && int(binary.BigEndian.Uint16(w[6:8])) == len(w)-8 &&
		(w[8] == 0xc0 || w[8] == 0xc4) && (w[9] == 1 || w[9] == 2 || w[9] == 3) && w[10]&0x30 == 0
}

func (a *binParser) decodeWrapperDatagram(e *ProtocolEvent, w []byte, src, dst uint16, explicit bool) bool {
	ports := [2]uint16{src, dst}
	// The registry supplies admission using real UDP ports. Explicit binding may
	// report malformed input; automatic admission requires wrapper-v1 or port hint.
	if !explicit && !wrapperPortStart(w, ports) && a.probeWrapperDatagram(w).Verdict != ProbeAccept {
		return false
	}
	e.nativeDLMSOrSLMPObservation = true
	e.Protocol, e.Profile, e.Admission, e.Completeness = "dlms-wrapper", wrapperProfile(w), "wire-signature", "message"
	if explicit {
		e.Admission = "explicit-decode-as"
	}
	if e.ID == 0 {
		e.ID = a.ids.Add(1)
	}
	key := binUDPKey{"wrapper/" + e.Source, "wrapper/" + e.Destination, e.Domain}
	if key.a > key.b {
		key.a, key.b = key.b, key.a
	}
	a.udpMu.Lock()
	defer a.udpMu.Unlock()
	store := a.udpSessions
	var el *list.Element
	if store != nil {
		el = store.entries[key]
		if el != nil {
			v := el.Value.(*binUDPEntry)
			if e.Timestamp.Sub(v.touched) >= wrapperIdleTTL {
				v.flow.retireDLMSUDP()
			}
		}
	}
	f := &binFlow{a: a, wrapper: &binDLMSWrapper{blocked: a.wrapperUntrackedRefusal}, protocol: "dlms-wrapper"}
	created := el == nil
	if el != nil {
		f = el.Value.(*binUDPEntry).flow
		e.FlowID = f.id
		e.Direction = 0
		if e.Source != f.endpoints[0] {
			e.Direction = 1
		}
		v := el.Value.(*binUDPEntry)
		if e.Timestamp.After(v.touched) {
			v.touched = e.Timestamp
		}
		store.lru.MoveToBack(el)
	}
	var err error
	limit := min(a.budget.MaxFrameBytes, a.config.MaxMessageBytes)
	if len(w) > limit {
		f.wrapper.invalidate()
		retained := f.wrapper.storage()
		if retained < f.sessionBytes {
			a.buffered.Add(retained - f.sessionBytes)
			f.sessionBytes = retained
		}
		err = wrapperError(ErrResourceExceeded, "datagram exceeds frame byte budget")
	} else {
		err = f.consumeWrapper(e.Direction, w, e)
		if f.wrapper.blocked {
			// Projection reservation preceded parsing; no parsed graph belongs
			// to the retired conversation once the event owns its fields.
			retained := f.wrapper.storage()
			if retained < f.sessionBytes {
				a.buffered.Add(retained - f.sessionBytes)
				f.sessionBytes = retained
			}
		}
	}
	// Incomplete/ambiguous ACSE requests retain a charged endpoint tombstone,
	// even without pending eligibility. A later same-endpoint AARQ has no nonce
	// with which to distinguish an old AARE from its own response.
	if err == nil && created && (f.wrapper.outstanding() > 0 || len(f.wrapper.associations) > 0) {
		if store != nil && len(store.entries) >= sessionCollectionLimit(a.budget.MaxCollectionElements) {
			err = wrapperError(ErrResourceExceeded, "UDP conversation limit")
		} else {
			if store == nil {
				store = &binUDPStore{entries: make(map[binUDPKey]*list.Element), clock: e.Timestamp}
				a.udpSessions = store
			}
			endpoints := [2]string{e.Source, e.Destination}
			if e.Direction == 1 {
				endpoints = [2]string{e.Destination, e.Source}
			}
			f.id, f.endpoints, f.domain = a.flows.Add(1), endpoints, e.Domain
			store.entries[key] = store.lru.PushBack(&binUDPEntry{key, f, e.Timestamp})
			e.FlowID = f.id
			created = false
		}
	}
	if created {
		var pe *ProtocolError
		if errors.As(err, &pe) && pe.Kind == ErrResourceExceeded && (explicit || wrapperUDPRefusalHint(w)) {
			// No charged key survives this refusal. A later request/reply cannot
			// prove a new generation of its invoke token. Already retained keys
			// keep their independently observed context.
			a.wrapperUntrackedRefusal = true
		}
		defer f.closeSession()
	}
	if err != nil {
		e.semanticFields, e.Session, e.semanticSession = nil, nil, nil
		e.TransactionID, e.ResponseTo = 0, 0
	}
	raw := w
	var typed *ProtocolError
	listRefused := wrapperUsesDataGraph(w) && errors.As(err, &typed) && typed.Kind == ErrResourceExceeded
	if listRefused {
		retained := f.wrapper.storage()
		if retained < f.sessionBytes {
			a.buffered.Add(retained - f.sessionBytes)
			f.sessionBytes = retained
		}
	}
	if len(w) > limit || f.sessionBytes == 0 || listRefused {
		raw = nil
		var typed *ProtocolError
		if errors.As(err, &typed) && typed.Kind == ErrResourceExceeded {
			a.limited.Add(uint64(len(w)))
		}
	}
	a.finishProtocolDatagram(e, raw, nil, err)
	if err != nil {
		e.Completeness = e.Status
	}
	return true
}

func (a *binParser) probeWrapper(w []byte) ProbeResult {
	if len(w) < 2 || w[0] != 0 || w[1] != 1 {
		return ProbeResult{Verdict: ProbeReject}
	}
	n, err := wrapperFrameSize(w, min(a.budget.MaxFrameBytes, a.config.MaxMessageBytes))
	if err != nil {
		return ProbeResult{Verdict: ProbeReject}
	}
	if n == 0 {
		if !wrapperIncompletePrefix(w, min(a.budget.MaxFrameBytes, a.config.MaxMessageBytes)) {
			return ProbeResult{Verdict: ProbeReject}
		}
		return probeNeed("dlms-wrapper", wrapperProbeVersion(w), len(w), max(8, len(w)+1))
	}
	temp := &binFlow{a: a}
	defer temp.closeSession()
	charge := int64(512) + 128*int64(n)
	if wrapperUsesDataGraph(w) {
		charge = 512 + wrapperProjection(w, n) + 256
	}
	if err := temp.reserveSession(charge); err != nil {
		return ProbeResult{Verdict: ProbeReject}
	}
	return probeDLMSWrapper(w[:n], a.budget.MaxFrameBytes)
}

func wrapperIncompletePrefix(w []byte, limit int) bool {
	if len(w) < 2 || w[0] != 0 || w[1] != 1 {
		return false
	}
	n, err := wrapperFrameSize(w, limit)
	return err == nil && n == 0 && (len(w) <= 8 || w[8] == 0xc0 || w[8] == 0xc4 || w[8] == 0xc1 || w[8] == 0xc5 || w[8] == 0xc3 || w[8] == 0xc7 || w[8] == 0xe0 || w[8] >= 0x60 && w[8] <= 0x64)
}
func (a *binParser) probeWrapperDatagram(w []byte) ProbeResult {
	n, err := wrapperFrameSize(w, min(a.budget.MaxFrameBytes, a.config.MaxMessageBytes))
	if err != nil || n == 0 || n != len(w) {
		return ProbeResult{Verdict: ProbeReject}
	}
	return a.probeWrapper(w)
}

func wrapperIsAction(w []byte) bool {
	return len(w) > 8 && w[0] == 0 && w[1] == 1 && (w[8] == 0xc3 || w[8] == 0xc7)
}
func wrapperRequestCommand(command byte) byte {
	if command == 0xc5 {
		return 0xc1
	}
	if command == 0xc7 {
		return 0xc3
	}
	return 0xc0
}

// Offset of one complete bounded Data field, if its optional/choice header
// advertises one. Structural decoding remains authoritative for malformed input.
func wrapperActionDataOffset(w []byte) int {
	if !wrapperIsAction(w) || len(w) < 11 || w[9] != 1 {
		return -1
	}
	if w[8] == 0xc3 && len(w) > 20 && w[20] == 1 {
		return 21
	}
	if w[8] == 0xc7 && len(w) > 13 && w[12] == 1 && w[13] == 0 {
		return 14
	}
	return -1
}
func wrapperDataAccessResultKnown(v byte) bool {
	switch v {
	case 0, 1, 2, 3, 4, 9, 11, 12, 13, 14, 15, 16, 17, 18, 19, 250:
		return true
	}
	return false
}

// Action-Result is distinct from Data-Access-Result: the long-SET codes
// 17/18/19 are not Action result enumerators in pinned COSEM ASN.1.
func wrapperActionResultKnown(v byte) bool {
	return v != 17 && v != 18 && v != 19 && wrapperDataAccessResultKnown(v)
}

// Observe selected unciphered Action-normal envelopes, not method permission,
// challenge verification or an authenticated COSEM association/device success.
func decodeWrapperAction(w []byte, limit, depth int) (*wrapperMessage, error) {
	bad := func(why string) (*wrapperMessage, error) { return nil, wrapperError(ErrMalformedMessage, why) }
	unsupported := func(why string) (*wrapperMessage, error) { return nil, wrapperError(ErrUnsupportedFeature, why) }
	p := w[8:]
	if len(p) < 3 {
		return bad("Action header truncated")
	}
	if p[1] != 1 && !wrapperIsActionList(w) {
		return unsupported("Action selected normal choice1 only")
	}
	if p[2]&0x30 != 0 {
		return unsupported("Action reserved invoke flags outside pinned reference")
	}
	v, src, dst, n := binary.BigEndian.Uint16(w), binary.BigEndian.Uint16(w[2:]), binary.BigEndian.Uint16(w[4:]), len(p)
	f := map[string]any{"wrapper_version": v, "source_wport": src, "destination_wport": dst, "payload_length": n, "wrapper_header_hex": hex.EncodeToString(w[:8]), "apdu_hex": hex.EncodeToString(p), "association_observed": false, "authentication_verified": false, "object_model_verified": false, "command": p[0], "service_choice": p[1], "invoke_id_and_priority": p[2], "invoke_id": p[2] & 15, "high_priority": p[2]&128 != 0, "confirmed_service": p[2]&64 != 0, "unused_flag_bits_raw": p[2] & 0x30}
	m := &wrapperMessage{fields: f, source: src, destination: dst, command: p[0], invoke: p[2] & 15, flags: p[2], request: p[0] == 0xc3, confirmed: p[2]&64 != 0, choice: 1, count: 1}
	f["operation_success_verified"] = false
	if wrapperIsActionList(w) {
		m.choice = 3
		if err := decodeWrapperActionList(m, p, limit, depth); err != nil {
			return nil, err
		}
		return m, nil
	}
	if m.request {
		if len(p) < 13 {
			return bad("Action-normal descriptor truncated")
		}
		if int8(p[11]) <= 0 {
			return unsupported("positive signed8 method profile")
		}
		if p[12] > 1 {
			return unsupported("Action optional parameters selected canonical0/1")
		}
		f["kind"], f["class_id"], f["logical_name_hex"], f["logical_name"], f["method_id"] = "ActionRequestNormal", binary.BigEndian.Uint16(p[3:5]), hex.EncodeToString(p[5:11]), fmt.Sprintf("%d.%d.%d.%d.%d.%d", p[5], p[6], p[7], p[8], p[9], p[10]), int8(p[11])
		f["method_invocation_parameters_present"] = p[12] == 1
		if p[12] == 0 {
			if len(p) != 13 {
				return bad("Action absent parameter has trailing bytes")
			}
		} else {
			c := wrapperListCursor{wire: p, at: 13, maxDepth: depth}
			data, err := c.data(limit, 0)
			if err != nil {
				return nil, err
			}
			if c.at != len(p) {
				return bad("Action parameter has trailing bytes")
			}
			f["parameter"] = data
		}
	} else {
		if len(p) < 5 {
			return bad("Action-normal result truncated")
		}
		if !wrapperActionResultKnown(p[3]) {
			return unsupported("Action result outside pinned enumeration")
		}
		if p[4] > 1 {
			return unsupported("Action return optional selected canonical0/1")
		}
		f["kind"], f["action_result"], f["action_result_success"], f["return_parameters_present"] = "ActionResponseNormal", p[3], p[3] == 0, p[4] == 1
		if p[4] == 0 {
			if len(p) != 5 {
				return bad("Action absent return has trailing bytes")
			}
		} else {
			if len(p) < 6 {
				return bad("Action return choice truncated")
			}
			f["return_choice_raw"] = p[5]
			switch p[5] {
			case 0:
				c := wrapperListCursor{wire: p, at: 6, maxDepth: depth}
				data, err := c.data(limit, 0)
				if err != nil {
					return nil, err
				}
				if c.at != len(p) {
					return bad("Action return Data has trailing bytes")
				}
				f["return_choice"], f["data"] = "data", data
			case 1:
				if len(p) != 7 {
					return bad("Action return access result missing or trailing bytes")
				}
				if !wrapperDataAccessResultKnown(p[6]) {
					return unsupported("Action access result outside pinned enumeration")
				}
				f["return_choice"], f["data_access_result"] = "data-access-result", p[6]
			default:
				return unsupported("Action return result selected choices0/1")
			}
		}
	}
	return m, nil
}

// Per-request close diagnostics use deterministic observation order. Credits for
// every retained key were admitted before insertion; Close does not infer a reply.
func (s *binDLMSWrapper) pendingOperations() []wrapperToken {
	keys := make([]wrapperToken, 0)
	for key, p := range s.seen {
		if p.pending && (p.command == 0xc1 || p.command == 0xc3) {
			keys = append(keys, key)
		}
	}
	sort.Slice(keys, func(i, j int) bool { return s.seen[keys[i]].id < s.seen[keys[j]].id })
	return keys
}
func wrapperOperationCloseFields(k wrapperToken, command, choice byte, count int) map[string]any {
	fields := map[string]any{"Outstanding": 1, "source_wport": k.source, "destination_wport": k.destination, "invoke_id": k.invoke, "request_command": command}
	if command == 0xc1 && choice == 4 || command == 0xc3 && choice == 3 {
		fields["service_choice"], fields["list_count"] = choice, uint64(count)
	}
	return fields
}

func wrapperIsSet(w []byte) bool {
	return len(w) > 8 && w[0] == 0 && w[1] == 1 && (w[8] == 0xc1 || w[8] == 0xc5)
}
func wrapperOperationName(command, choice byte) string {
	if command == 0xc1 && choice == 2 {
		return "Set-with-data-block"
	}
	if command == 0xc3 && choice == 3 {
		return "Action-with-list"
	}
	if command == 0xc1 && choice == 4 {
		return "Set-with-list"
	}
	if command == 0xc1 {
		return "Set"
	}
	return "Action"
}
func wrapperOperationProfile(command, choice byte) string {
	if command == 0xc1 && choice == 2 {
		return "dlms-wrapper-v1-set-block"
	}
	if command == 0xc3 && choice == 3 {
		return "dlms-wrapper-v1-action-list"
	}
	if command == 0xc1 && choice == 4 {
		return "dlms-wrapper-v1-set-list"
	}
	if command == 0xc1 {
		return "dlms-wrapper-v1-set-normal"
	}
	return "dlms-wrapper-v1-action-normal"
}
func wrapperOperationDataOffset(w []byte) int {
	if wrapperIsSet(w) && len(w) > 20 && w[8] == 0xc1 && w[9] == 1 {
		if w[20] == 0 {
			return 21
		}
		if w[20] == 1 {
			return 22
		} // firstData is selector parameters; value follows it.
	}
	return wrapperActionDataOffset(w)
}

// SET-normal observes a complete Data proposal and a literal access result.
// It cannot establish authorization, object meaning or a successful device write.
func decodeWrapperSet(w []byte, limit, depth int) (*wrapperMessage, error) {
	bad := func(why string) (*wrapperMessage, error) { return nil, wrapperError(ErrMalformedMessage, why) }
	unsupported := func(why string) (*wrapperMessage, error) { return nil, wrapperError(ErrUnsupportedFeature, why) }
	p := w[8:]
	if len(p) < 3 {
		return bad("Set service header truncated")
	}
	if p[1] != 1 && !wrapperIsSetList(w) && !wrapperIsSetBlock(w) {
		return unsupported("Set selected normal choice1 only")
	}
	if p[2]&0x30 != 0 {
		return unsupported("Set reserved invoke flags outside pinned reference")
	}
	v, src, dst, n := binary.BigEndian.Uint16(w), binary.BigEndian.Uint16(w[2:]), binary.BigEndian.Uint16(w[4:]), len(p)
	f := map[string]any{"wrapper_version": v, "source_wport": src, "destination_wport": dst, "payload_length": n, "wrapper_header_hex": hex.EncodeToString(w[:8]), "apdu_hex": hex.EncodeToString(p), "association_observed": false, "authentication_verified": false, "object_model_verified": false, "command": p[0], "service_choice": p[1], "invoke_id_and_priority": p[2], "invoke_id": p[2] & 15, "high_priority": p[2]&128 != 0, "confirmed_service": p[2]&64 != 0, "unused_flag_bits_raw": p[2] & 0x30}
	f["operation_success_verified"] = false
	m := &wrapperMessage{fields: f, source: src, destination: dst, command: p[0], invoke: p[2] & 15, flags: p[2], request: p[0] == 0xc1, confirmed: p[2]&64 != 0, choice: 1, count: 1}
	if wrapperIsSetBlock(w) {
		if err := decodeWrapperSetBlock(m, p, limit, depth); err != nil {
			return nil, err
		}
		return m, nil
	}
	if wrapperIsSetList(w) {
		m.choice = 4
		if err := decodeWrapperSetList(m, p, limit, depth); err != nil {
			return nil, err
		}
		return m, nil
	}
	if m.request {
		if len(p) < 13 {
			return bad("Set-normal descriptor truncated")
		}
		if int8(p[11]) <= 0 {
			return unsupported("positive signed8 Set attribute profile")
		}
		if p[12] > 1 {
			return unsupported("Set optional access selection must be canonical0/1")
		}
		f["kind"], f["class_id"], f["logical_name_hex"], f["logical_name"], f["attribute_id"], f["selective_access"] = "SetRequestNormal", binary.BigEndian.Uint16(p[3:5]), hex.EncodeToString(p[5:11]), fmt.Sprintf("%d.%d.%d.%d.%d.%d", p[5], p[6], p[7], p[8], p[9], p[10]), int8(p[11]), p[12] == 1
		c := wrapperListCursor{wire: p, at: 13, maxDepth: depth}
		if p[12] == 1 {
			selector, e := c.take(1)
			if e != nil {
				return nil, e
			}
			parameter, e := c.data(limit, 0)
			if e != nil {
				return nil, e
			}
			f["access_selection_raw"], f["access_selector"], f["access_parameters"], f["selector_semantics_verified"] = p[12], selector[0], parameter, false
		}
		data, err := c.data(limit, 0)
		if err != nil {
			return nil, err
		}
		if c.at != len(p) {
			return bad("Set Data has trailing bytes")
		}
		f["data"] = data
	} else {
		if len(p) != 4 {
			return bad("Set-normal result missing or trailing bytes")
		}
		if !wrapperDataAccessResultKnown(p[3]) {
			return unsupported("Set access result outside pinned enumeration")
		}
		f["kind"], f["data_access_result"], f["result_success"] = "SetResponseNormal", p[3], p[3] == 0
	}
	return m, nil
}
