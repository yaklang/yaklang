package ssa

import (
	"testing"

	"github.com/stretchr/testify/require"
)

// The loop phi includes the old member as an edge. Reading phi.next while
// replacing old must not turn that originally-leaf member into fresh source
// work: each read would otherwise synthesize another next and recurse forever.
func TestReplaceMemberCallDoesNotExpandReadGeneratedMembers(t *testing.T) {
	prog, builder := newTestBuilder(t)
	holder := builder.EmitUndefined("cursor")
	key := builder.EmitConstInst("next")
	member := builder.ReadMemberCallValue(holder, key)
	require.False(t, member.IsObject())
	replacement := builder.EmitPhi("cursor", []Value{holder, member})
	before := prog.Cache.CountInstruction()

	result := ReplaceMemberCall(holder, replacement)

	require.NotEmpty(t, result)
	require.Less(t, prog.Cache.CountInstruction()-before, 30,
		"replacement must visit the original source graph, not members generated by its own reads")
	got := result[checkCanMemberCallExist(replacement, key).name]
	require.NotNil(t, got)
	phi, ok := ToPhi(got)
	require.True(t, ok, "the generated member must still merge the original loop edges")
	require.Len(t, phi.Edge, 2)
}
