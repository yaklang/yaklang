func moduleRoot() (string, error) {
	root, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(root, "go.mod")); err == nil {
			return root, nil
		}
		parent := filepath.Dir(root)
		if parent == root {
			return "", fmt.Errorf("cannot locate go.mod")
		}
		root = parent
	}
}

func analyze(root, kind string, files map[string]builtinmetadata.File, recipe string) (*builtinmetadata.Bundle, error) {
	catalog := &builtinmetadata.Bundle{Version: builtinmetadata.Version, Kind: kind, Recipe: recipe, Files: files, SourceHash: builtinmetadata.Fingerprint(files, recipe), Entries: map[string]builtinmetadata.Entry{}}
	sourceDir := filepath.Join(root, specFor(kind).dir)
	add := func(key, path string, value builtinmetadata.Metadata) {
		relative, _ := filepath.Rel(sourceDir, path)
		catalog.Entries[key] = builtinmetadata.Entry{Script: filepath.ToSlash(relative), Metadata: value}
	}
	if kind == "aitool" {
		tools := filepath.Join(root, "common/ai/aid/aitool/buildinaitools/yakscripttools/yakscriptforai")
		if err := filepath.WalkDir(tools, func(path string, d fs.DirEntry, err error) error {
			if err != nil || d.IsDir() || filepath.Ext(path) != ".yak" {
				return err
			}
			code, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			name := strings.TrimSuffix(d.Name(), ".yak")
			tool := yakscripttools.LoadYakScriptToAiTools(name, string(code))
			if tool == nil {
				return fmt.Errorf("analyze builtin AI tool %s", path)
			}
			// MCP property maps have no semantic order; make generated bytes stable.
			var schema any
			if err := json.Unmarshal([]byte(tool.Params), &schema); err != nil {
				return err
			}
			params, err := json.Marshal(schema)
			if err != nil {
				return err
			}
			add("tool:"+name, path, builtinmetadata.Metadata{
				VerboseName: tool.VerboseName, VerboseNameZh: tool.VerboseNameZh,
				Description: tool.Description, Keywords: tool.Keywords, Usage: tool.Usage,
				Parameters: params, EnableAIOutputLog: tool.EnableAIOutputLog,
			})
			return nil
		}); err != nil {
			return nil, err
		}

	}
	if kind == "coreplugin" {
		// Read registration calls so names and plugin types have one source of truth.
		registrations, err := parser.ParseFile(token.NewFileSet(), filepath.Join(root, "common/coreplugin/coreplugin.go"), nil, 0)
		if err != nil {
			return nil, err
		}
		var generationErr error
		ast.Inspect(registrations, func(node ast.Node) bool {
			if generationErr != nil {
				return false
			}
			call, ok := node.(*ast.CallExpr)
			if !ok {
				return true
			}
			fn, ok := call.Fun.(*ast.Ident)
			if !ok || fn.Name != "registerBuildInPlugin" {
				return true
			}
			needsParameters := false
			for _, arg := range call.Args[2:] {
				option, ok := arg.(*ast.CallExpr)
				if !ok || len(option.Args) != 1 {
					continue
				}
				name, ok := option.Fun.(*ast.Ident)
				value, literal := option.Args[0].(*ast.Ident)
				if ok && literal && name.Name == "withPluginEnableGenerateParam" && value.Name == "true" {
					needsParameters = true
				}
			}
			if !needsParameters {
				return false
			}
			literal := func(i int) (string, error) {
				if i < len(call.Args) {
					if value, ok := call.Args[i].(*ast.BasicLit); ok && value.Kind == token.STRING {
						return strconv.Unquote(value.Value)
					}
				}
				return "", fmt.Errorf("core plugin registration argument %d must be a string literal", i)
			}
			pluginType, err := literal(0)
			if err != nil {
				generationErr = err
				return false
			}
			name, err := literal(1)
			if err != nil {
				generationErr = err
				return false
			}
			code, err := os.ReadFile(filepath.Join(root, "common/coreplugin/base-yak-plugin", name+".yak"))
			if err != nil {
				generationErr = err
				return false
			}
			prog, err := static_analyzer.SSAParse(string(code), pluginType)
			if err != nil {
				generationErr = fmt.Errorf("analyze core plugin %s: %w", name, err)
				return false
			}
			params, envKeys, err := information.GenerateParameterFromProgram(prog)
			generationErr = err
			add("plugin:"+pluginType+":"+name, filepath.Join(root, "common/coreplugin/base-yak-plugin", name+".yak"), builtinmetadata.Metadata{Parameters: unquoteJSON(params), EnvironmentKeys: unquoteJSON(envKeys)})
			return false
		})
		if generationErr != nil {
			return nil, generationErr
		}

	}
	if kind == "forge" {
		forgeSource, err := parser.ParseFile(token.NewFileSet(), filepath.Join(root, "common/ai/aiforge/buildin_forge.go"), nil, 0)
		if err != nil {
			return nil, err
		}
		registeredForges := map[string]bool{}
		ast.Inspect(forgeSource, func(node ast.Node) bool {
			call, ok := node.(*ast.CallExpr)
			if !ok || len(call.Args) != 1 {
				return true
			}
			fn, ok := call.Fun.(*ast.Ident)
			name, literal := call.Args[0].(*ast.BasicLit)
			if ok && literal && fn.Name == "registerBuildInForge" && name.Kind == token.STRING {
				value, err := strconv.Unquote(name.Value)
				if err == nil {
					registeredForges[value] = true
				}
			}
			return true
		})
		forges := filepath.Join(root, "common/ai/aiforge/buildinforge")
		if err := filepath.WalkDir(forges, func(path string, d fs.DirEntry, err error) error {
			if err != nil || d.IsDir() || filepath.Ext(path) != ".yak" {
				return err
			}
			name := strings.TrimSuffix(d.Name(), ".yak")
			// Config forges read <name>/<name>.yak; other files (including
			// underscore-prefixed drafts) are not analyzed during startup.
			if !registeredForges[name] {
				return nil
			}
			code, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			prog, err := static_analyzer.SSAParse(string(code), "yak")
			if err != nil {
				return fmt.Errorf("analyze builtin forge %s: %w", path, err)
			}
			meta, err := metadata.ParseYakScriptMetadataProg(name, prog)
			if err != nil {
				return err
			}
			params, _, err := information.GenerateParameterFromProgram(prog)
			if err != nil {
				return err
			}
			if unquoted, err := strconv.Unquote(params); err == nil {
				params = unquoted
			}
			add("forge:"+name, path, builtinmetadata.Metadata{
				VerboseName: meta.VerboseName, Description: meta.Description,
				Keywords: strings.Join(meta.Keywords, ","), Parameters: json.RawMessage(params),
			})
			return nil
		}); err != nil {
			return nil, err
		}
	}
	if kind == "syntaxflow" {
		for name := range files {
			if filepath.Ext(name) != ".sf" {
				continue
			}
			code, err := os.ReadFile(filepath.Join(sourceDir, filepath.FromSlash(name)))
			if err != nil {
				return nil, err
			}
			rule, err := sfdb.CheckSyntaxFlowRuleContent(string(code))
			if err != nil {
				return nil, fmt.Errorf("analyze %s: %w", name, err)
			}
			raw, err := sfvm.EncodeBuiltinRuleMetadata(rule)
			if err != nil {
				return nil, err
			}
			catalog.Entries["sf:"+name] = builtinmetadata.Entry{Script: name, Metadata: builtinmetadata.Metadata{SyntaxFlowRule: raw}}
		}
	}
	currentRecipe, err := recipeFor(root, kind)
	if err != nil {
		return nil, err
	}
	if currentRecipe != recipe {
		return nil, fmt.Errorf("%s registration changed during generation", kind)
	}
	return catalog, nil
}

func unquoteJSON(value string) json.RawMessage {
	if value == "" {
		return nil
	}
	decoded, err := strconv.Unquote(value)
	if err != nil {
		return json.RawMessage(value)
	}
	return json.RawMessage(decoded)
}

var resourceSpecs = []struct{ kind, dir, constant string }{
	{"aitool", "common/ai/aid/aitool/buildinaitools/yakscripttools/yakscriptforai", "ExistedBuildInAIToolEmbedFSHash"},
	{"coreplugin", "common/coreplugin/base-yak-plugin", "ExistedCorePluginEmbedFSHash"},
	{"forge", "common/ai/aiforge/buildinforge", "ExistedBuildInForgeEmbedFSHash"},
	{"syntaxflow", "common/syntaxflow/sfbuildin/buildin", "ExistedSyntaxFlowEmbedFSHash"},
}

func specFor(kind string) struct{ kind, dir, constant string } {
	for _, spec := range resourceSpecs {
		if spec.kind == kind {
			return spec
		}
	}
	panic("unknown script set: " + kind)
}

// Registration changes are part of the source recipe, including flags and
// defaults that affect DB synchronization. Unrelated Go edits do not invalidate.
func recipeFor(root, kind string) (string, error) {
	var file, fn string
	switch kind {
	case "syntaxflow":
		// A compiler edit invalidates precompiled instructions even when every
		// rule is unchanged. Do this at build time, never at engine startup.
		inputs := map[string]string{}
		for _, dir := range []string{"common/syntaxflow/sf", "common/syntaxflow/sfvm"} {
			names, err := filepath.Glob(filepath.Join(root, dir, "*.go"))
			if err != nil {
				return "", err
			}
			if len(names) == 0 {
				return "", fmt.Errorf("missing compiler sources: %s", dir)
			}
			for _, name := range names {
				if strings.HasSuffix(name, "_test.go") {
					continue
				}
				data, err := os.ReadFile(name)
				if err != nil {
					return "", err
				}
				relative, _ := filepath.Rel(root, name)
				inputs[filepath.ToSlash(relative)] = builtinmetadata.Digest(data)
			}
		}
		data, err := os.ReadFile(filepath.Join(root, "common/schema/syntaxflow_rule.go"))
		if err != nil {
			return "", err
		}
		inputs["common/schema/syntaxflow_rule.go"] = builtinmetadata.Digest(data)
		raw, err := json.Marshal(inputs)
		if err != nil {
			return "", err
		}
		return builtinmetadata.Digest(raw), nil
	case "coreplugin":
		file = "common/coreplugin/coreplugin.go"
		fn = "registerBuildInPlugin"
	case "forge":
		file = "common/ai/aiforge/buildin_forge.go"
		fn = "registerBuildInForge"
	default:
		return kind, nil
	}
	set := token.NewFileSet()
	parsed, err := parser.ParseFile(set, filepath.Join(root, file), nil, 0)
	if err != nil {
		return "", err
	}
	var calls []string
	ast.Inspect(parsed, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}
		id, ok := call.Fun.(*ast.Ident)
		if !ok || id.Name != fn {
			return true
		}
		var buf bytes.Buffer
		if err := format.Node(&buf, set, call); err != nil {
			return false
		}
		calls = append(calls, buf.String())
		return false
	})
	sort.Strings(calls)
	data, _ := json.Marshal(calls)
	return builtinmetadata.Digest(data), nil
}

// updateSet is testable without invoking any SSA parser. Only a changed or
// invalid source/metadata pair calls build. All results are ready before writes.
func updateSet(sourceDir, outputDir, kind, constant, recipe string, check, force bool, build func(map[string]builtinmetadata.File) (*builtinmetadata.Bundle, error)) (bool, error) {
	files, err := builtinmetadata.Scan(sourceDir)
	if err != nil {
		return false, err
	}
	bundlePath := filepath.Join(outputDir, kind+"-metadata.json")
	packedPath := bundlePath + ".br"
	hashPath := filepath.Join(outputDir, kind+"-hash.go")
	oldHash, err := os.ReadFile(hashPath)
	if err != nil {
		return false, err
	}
	marker := "const " + constant + " string = "
	expected := ""
	for _, line := range strings.Split(string(oldHash), "\n") {
		if strings.HasPrefix(line, marker) {
			expected, _ = strconv.Unquote(strings.TrimPrefix(line, marker))
			break
		}
	}
	if expected == "" {
		return false, fmt.Errorf("missing hash constant: %s", constant)
	}
	if !force {
		if data, err := os.ReadFile(bundlePath); err == nil {
			if previous, err := builtinmetadata.Parse(data, kind); err == nil && previous.Matches(files, recipe) {
				// Reuse an existing verified build artifact without running the
				// expensive compressor again. Compare canonical text as well as
				// the source manifest so a metadata edit cannot hide behind it.
				if packed, err := os.ReadFile(packedPath); err == nil {
					if verified, err := builtinmetadata.Decode(packed, kind, expected); err == nil {
						a, errA := json.Marshal(previous)
						b, errB := json.Marshal(verified)
						if errA == nil && errB == nil && bytes.Equal(a, b) {
							return false, nil
						}
					}
				}
				packed, err := builtinmetadata.Encode(previous)
				if err != nil {
					return false, err
				}
				if builtinmetadata.Digest(packed) == expected {
					if !check {
						err = writeGenerated(packedPath, packed)
					}
					return false, err
				}
			}
		}
	}
	if check {
		return false, fmt.Errorf("%s metadata is stale; refresh embedded resource hashes", kind)
	}
	bundle, err := build(files)
	if err != nil {
		return false, err
	}
	data, err := builtinmetadata.Encode(bundle)
	if err != nil {
		return false, err
	}
	// Compression can take seconds. Verify the source again immediately before
	// publishing either artifact or its hash.
	latest, err := builtinmetadata.Scan(sourceDir)
	if err != nil {
		return false, err
	}
	if !bundle.Matches(latest, recipe) {
		return false, fmt.Errorf("%s sources changed during generation", kind)
	}
	if _, err := builtinmetadata.Decode(data, kind, ""); err != nil {
		return false, err
	}
	text, err := builtinmetadata.Text(bundle)
	if err != nil {
		return false, err
	}
	lines := strings.Split(string(oldHash), "\n")
	for i, line := range lines {
		if strings.HasPrefix(line, marker) {
			lines[i] = marker + strconv.Quote(builtinmetadata.Digest(data))
		}
	}
	if err := writeGenerated(bundlePath, text); err != nil {
		return false, err
	}
	if err := writeGenerated(packedPath, data); err != nil {
		return false, err
	}
	if err := writeGenerated(hashPath, []byte(strings.Join(lines, "\n"))); err != nil {
		return false, err
	}
	return true, nil
}

func main() {
	check := flag.Bool("check", false, "verify source manifests, compressed metadata and hashes without parsing scripts")
	force := flag.Bool("force", false, "rebuild even when the script set is unchanged")
	only := flag.String("kind", "", "refresh only aitool/coreplugin/forge/syntaxflow")
	flag.Parse()
	root, err := moduleRoot()
	if err != nil {
		panic(err)
	}
	for _, spec := range resourceSpecs {
		if *only != "" && *only != spec.kind {
			continue
		}
		recipe, err := recipeFor(root, spec.kind)
		if err != nil {
			panic(err)
		}
		changed, err := updateSet(filepath.Join(root, spec.dir), filepath.Join(root, "common/consts"), spec.kind, spec.constant, recipe, *check, *force, func(files map[string]builtinmetadata.File) (*builtinmetadata.Bundle, error) {
			return analyze(root, spec.kind, files, recipe)
		})
		if err != nil {
			panic(err)
		}
		if changed {
			fmt.Printf("%s: regenerated metadata and hash\n", spec.kind)
		} else {
			fmt.Printf("%s: unchanged (no analysis or writes)\n", spec.kind)
		}
	}
}

func writeGenerated(path string, data []byte) error {
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, data) {
		return nil
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".metadata-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err = tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err = tmp.Chmod(0644); err != nil {
		tmp.Close()
		return err
	}
	if err = tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}
