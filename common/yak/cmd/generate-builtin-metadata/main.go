func moduleRoot() (string, error) {
	root, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(root, "go.mod")); err == nil {
			return root, nil
		}
		parent := filepath.Dir(root)
		if parent == root {
			return "", fmt.Errorf("cannot locate go.mod")
		}
		root = parent
	}
}

func generate(root string) ([]byte, error) {
	catalog := builtinmetadata.Catalog{Version: builtinmetadata.Version, Entries: map[string]builtinmetadata.Entry{}}
	add := func(key, code string, value builtinmetadata.Metadata) {
		catalog.Entries[key] = builtinmetadata.Entry{SourceSHA256: builtinmetadata.SourceHash(code), Metadata: value}
	}
	tools := filepath.Join(root, "common/ai/aid/aitool/buildinaitools/yakscripttools/yakscriptforai")
	if err := filepath.WalkDir(tools, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || filepath.Ext(path) != ".yak" {
			return err
		}
		code, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		name := strings.TrimSuffix(d.Name(), ".yak")
		tool := yakscripttools.LoadYakScriptToAiTools(name, string(code))
		if tool == nil {
			return fmt.Errorf("analyze builtin AI tool %s", path)
		}
		// MCP property maps have no semantic order; make generated bytes stable.
		var schema any
		if err := json.Unmarshal([]byte(tool.Params), &schema); err != nil {
			return err
		}
		params, err := json.Marshal(schema)
		if err != nil {
			return err
		}
		add("tool:"+name, string(code), builtinmetadata.Metadata{
			VerboseName: tool.VerboseName, VerboseNameZh: tool.VerboseNameZh,
			Description: tool.Description, Keywords: tool.Keywords, Usage: tool.Usage,
			Parameters: string(params), EnableAIOutputLog: tool.EnableAIOutputLog,
		})
		return nil
	}); err != nil {
		return nil, err
	}

	// Read registration calls so names and plugin types have one source of truth.
	registrations, err := parser.ParseFile(token.NewFileSet(), filepath.Join(root, "common/coreplugin/coreplugin.go"), nil, 0)
	if err != nil {
		return nil, err
	}
	var generationErr error
	ast.Inspect(registrations, func(node ast.Node) bool {
		if generationErr != nil {
			return false
		}
		call, ok := node.(*ast.CallExpr)
		if !ok {
			return true
		}
		fn, ok := call.Fun.(*ast.Ident)
		if !ok || fn.Name != "registerBuildInPlugin" {
			return true
		}
		needsParameters := false
		for _, arg := range call.Args[2:] {
			option, ok := arg.(*ast.CallExpr)
			if !ok || len(option.Args) != 1 {
				continue
			}
			name, ok := option.Fun.(*ast.Ident)
			value, literal := option.Args[0].(*ast.Ident)
			if ok && literal && name.Name == "withPluginEnableGenerateParam" && value.Name == "true" {
				needsParameters = true
			}
		}
		if !needsParameters {
			return false
		}
		literal := func(i int) (string, error) {
			if i < len(call.Args) {
				if value, ok := call.Args[i].(*ast.BasicLit); ok && value.Kind == token.STRING {
					return strconv.Unquote(value.Value)
				}
			}
			return "", fmt.Errorf("core plugin registration argument %d must be a string literal", i)
		}
		pluginType, err := literal(0)
		if err != nil {
			generationErr = err
			return false
		}
		name, err := literal(1)
		if err != nil {
			generationErr = err
			return false
		}
		code, err := os.ReadFile(filepath.Join(root, "common/coreplugin/base-yak-plugin", name+".yak"))
		if err != nil {
			generationErr = err
			return false
		}
		prog, err := static_analyzer.SSAParse(string(code), pluginType)
		if err != nil {
			generationErr = fmt.Errorf("analyze core plugin %s: %w", name, err)
			return false
		}
		params, envKeys, err := information.GenerateParameterFromProgram(prog)
		generationErr = err
		add("plugin:"+pluginType+":"+name, string(code), builtinmetadata.Metadata{Parameters: params, EnvironmentKeys: envKeys})
		return false
	})
	if generationErr != nil {
		return nil, generationErr
	}

	forgeSource, err := parser.ParseFile(token.NewFileSet(), filepath.Join(root, "common/ai/aiforge/buildin_forge.go"), nil, 0)
	if err != nil {
		return nil, err
	}
	registeredForges := map[string]bool{}
	ast.Inspect(forgeSource, func(node ast.Node) bool {
		call, ok := node.(*ast.CallExpr)
		if !ok || len(call.Args) != 1 {
			return true
		}
		fn, ok := call.Fun.(*ast.Ident)
		name, literal := call.Args[0].(*ast.BasicLit)
		if ok && literal && fn.Name == "registerBuildInForge" && name.Kind == token.STRING {
			value, err := strconv.Unquote(name.Value)
			if err == nil {
				registeredForges[value] = true
			}
		}
		return true
	})
	forges := filepath.Join(root, "common/ai/aiforge/buildinforge")
	if err := filepath.WalkDir(forges, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || filepath.Ext(path) != ".yak" {
			return err
		}
		name := strings.TrimSuffix(d.Name(), ".yak")
		// Config forges read <name>/<name>.yak; other files (including
		// underscore-prefixed drafts) are not analyzed during startup.
		if !registeredForges[name] {
			return nil
		}
		code, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		prog, err := static_analyzer.SSAParse(string(code), "yak")
		if err != nil {
			return fmt.Errorf("analyze builtin forge %s: %w", path, err)
		}
		meta, err := metadata.ParseYakScriptMetadataProg(name, prog)
		if err != nil {
			return err
		}
		params, _, err := information.GenerateParameterFromProgram(prog)
		if err != nil {
			return err
		}
		if unquoted, err := strconv.Unquote(params); err == nil {
			params = unquoted
		}
		add("forge:"+name, string(code), builtinmetadata.Metadata{
			VerboseName: meta.VerboseName, Description: meta.Description,
			Keywords: strings.Join(meta.Keywords, ","), Parameters: params,
		})
		return nil
	}); err != nil {
		return nil, err
	}
	sources := map[string]string{}
	for _, spec := range resourceSpecs {
		var options []filesys.Option
		if spec.ext != "" {
			options = append(options, filesys.WithIncludeExts(spec.ext))
		}
		hash, err := filesys.CreateLocalFSHash(filepath.Join(root, spec.dir), options...)
		if err != nil {
			return nil, err
		}
		sources[spec.prefix] = hash
	}
	catalog.PrepareResourceHashes(sources)
	data, err := json.MarshalIndent(catalog, "", "  ")
	return append(data, '\n'), err
}

func main() {
	check := flag.Bool("check", false, "verify generated metadata and resource hashes without writing")
	flag.Parse()
	root, err := moduleRoot()
	if err != nil {
		panic(err)
	}
	data, err := generate(root)
	if err != nil {
		panic(err)
	}
	path := filepath.Join(root, "common/consts/builtin-metadata-hash.go")
	source, err := catalogSource(data)
	if err != nil {
		panic(err)
	}
	update := func(path string, content []byte) error {
		if *check {
			existing, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			if !bytes.Equal(existing, content) {
				return fmt.Errorf("generated metadata/hash is stale: %s", path)
			}
			return nil
		}
		return writeGenerated(path, content)
	}
	if err := update(path, source); err != nil {
		panic(err)
	}
	// Update the existing hash files without changing their documented format.
	var catalog builtinmetadata.Catalog
	if err := json.Unmarshal(data, &catalog); err != nil {
		panic(err)
	}
	for _, spec := range resourceSpecs {
		hashPath := filepath.Join(root, "common/consts", spec.file+"-hash.go")
		old, err := os.ReadFile(hashPath)
		if err != nil {
			panic(err)
		}
		marker := "const " + spec.constant + " string = "
		lines := strings.Split(string(old), "\n")
		found := false
		for i, line := range lines {
			if strings.HasPrefix(line, marker) {
				lines[i] = marker + strconv.Quote(catalog.SourceHashes[spec.prefix])
				found = true
			}
		}
		if !found {
			panic("missing hash constant: " + spec.constant)
		}
		if err := update(hashPath, []byte(strings.Join(lines, "\n"))); err != nil {
			panic(err)
		}
	}
	fmt.Printf("generated builtin metadata and all resource hashes (%d bytes)\n", len(data))
}

var resourceSpecs = []struct{ prefix, dir, ext, file, constant string }{
	{"tool:", "common/ai/aid/aitool/buildinaitools/yakscripttools/yakscriptforai", ".yak", "aitool", "ExistedBuildInAIToolEmbedFSHash"},
	{"plugin:", "common/coreplugin/base-yak-plugin", ".yak", "coreplugin", "ExistedCorePluginEmbedFSHash"},
	{"forge:", "common/ai/aiforge/buildinforge", "", "forge", "ExistedBuildInForgeEmbedFSHash"},
	{"syntaxflow:", "common/syntaxflow/sfbuildin/buildin", ".sf", "syntaxflow", "ExistedSyntaxFlowEmbedFSHash"},
}

func writeGenerated(path string, data []byte) error {
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, data) {
		return nil
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".metadata-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err = tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err = tmp.Chmod(0644); err != nil {
		tmp.Close()
		return err
	}
	if err = tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}

// Keep the catalog beside the existing *-hash.go outputs so CI's hash refresh
// commit includes both from the same checkout. Plain builds exclude the data.
func catalogSource(data []byte) ([]byte, error) {
	var out strings.Builder
	out.WriteString("// Code generated by generate-builtin-metadata DO NOT EDIT.\n//go:build gzip_embed\n\npackage consts\n\nconst BuiltinMetadataCatalog = \"\"")
	for _, line := range strings.SplitAfter(string(data), "\n") {
		if line != "" {
			out.WriteString(" +\n" + strconv.Quote(line))
		}
	}
	out.WriteByte('\n')
	return format.Source([]byte(out.String()))
}
