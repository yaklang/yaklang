type sourceCheck struct {
	Path         string  `json:"path"`
	Error        string  `json:"error,omitempty"`
	Stubs        int     `json:"stubs,omitempty"`
	Suppressed   bool    `json:"suppressed,omitempty"`
	SHA256       string  `json:"sha256,omitempty"`
	Reused       bool    `json:"verification_reused,omitempty"`
	Kind         string  `json:"kind"`
	ParseSeconds float64 `json:"parse_seconds"`
	CheckSeconds float64 `json:"check_seconds"`
	ReadSeconds  float64 `json:"read_seconds"`
}

type verification struct {
	Files                 int              `json:"files"`
	Checked               int              `json:"checked"`
	UniqueChecks          int              `json:"unique_checks"`
	ReusedChecks          int              `json:"reused_checks"`
	MaterializationErrors int64            `json:"materialization_errors"`
	SyntaxFailures        int              `json:"syntax_failures"`
	StubMethods           int              `json:"stub_methods"`
	StubFiles             int              `json:"stub_files"`
	Suppressed            int              `json:"suppressed"`
	PrepareSeconds        float64          `json:"prepare_seconds"`
	VerifySeconds         float64          `json:"verify_seconds"`
	HeapAlloc             uint64           `json:"heap_alloc_bytes"`
	HeapInuse             uint64           `json:"heap_inuse_bytes"`
	SourceBytes           int64            `json:"source_bytes"`
	Preparation           ssautils.Timings `json:"preparation"`
	JavaFiles             int              `json:"java_files"`
	FrontendFiles         int              `json:"frontend_covered_files"`
	FrontendCalls         int              `json:"frontend_calls"`
	FrontendFailures      int              `json:"frontend_failures"`
	DecompilerRefusals    int              `json:"decompiler_refusals"`
	EmptyUnits            int              `json:"empty_units"`
	ReadFailures          int              `json:"read_failures"`
	JavaWorkerSeconds     float64          `json:"java_worker_seconds"`
	CheckWorkerSeconds    float64          `json:"check_worker_seconds"`
	ReadWorkerSeconds     float64          `json:"read_worker_seconds"`
	ManifestWriteSeconds  float64          `json:"manifest_write_seconds"`
	Issues                []sourceCheck    `json:"issues,omitempty"`
}

// A stubbed method body carries the marker as a quoted string literal, while a
// stubbed static initializer can only carry it as a comment (there is no body
// to throw from). Counting one form alone would report a class whose <clinit>
// was dropped as a clean file with zero stubs.
const (
	stubMethodMarker = `"yak-decompiler: undecompilable method body"`
	stubClinitMarker = `yak-decompiler: undecompilable <clinit>`
)

func countStubs(src []byte) int {
	return bytes.Count(src, []byte(stubMethodMarker)) + bytes.Count(src, []byte(stubClinitMarker))
}

func verifySource(path string, src []byte, cache *ssa.AntlrCache) sourceCheck {
	check := sourceCheck{Path: path, Kind: "java", Stubs: countStubs(src)}
	if bytes.Contains(src, []byte("// decompile parse failed")) || bytes.Contains(src, []byte("// decompile dump failed")) {
		check.Kind = "decompiler_refusal"
		check.Error = strings.TrimSpace(string(src))
		return check
	}
	// GetAntlrCache creates and retains a new DFA every call. Verification must
	// reuse the worker cache passed in, then reset it after the AST is dropped.
	parseStarted := time.Now()
	ast, err := java2ssa.FrontendRaw(string(src), cache)
	check.ParseSeconds = time.Since(parseStarted).Seconds()
	if err != nil {
		check.Kind = "frontend_error"
		check.Error = err.Error()
		if len(check.Error) > 2000 {
			check.Error = check.Error[:2000]
		}
		return check
	}
	if ast == nil || len(ast.AllTypeDeclaration()) == 0 && ast.ModuleDeclaration() == nil {
		if bytes.Contains(src, []byte("folded into")) || bytes.Contains(src, []byte("regenerated by javac")) ||
			bytes.Contains(src, []byte("javac regenerates its binary class")) ||
			bytes.Contains(src, []byte("// original method-local declaration regenerated in its proved owning method")) ||
			bytes.Contains(src, []byte("// original enum-switch table regenerated by the proved source unit")) {
			check.Suppressed = true
			check.Kind = "ownership_suppressed"
		} else if filepath.Base(path) == "package-info.java" && ast != nil && ast.PackageDeclaration() != nil {
			check.Kind = "descriptor"
			// package-info.java is a legal compilation unit with no type declaration.
			// A dropped class body still fails: that path is not named package-info.java.
		} else {
			check.Kind = "empty_unit"
			check.Error = "empty compilation unit without a source-ownership suppression marker"
		}
	}
	return check
}

func verifyTree(tree *filesys.VirtualFS, workers int, out string) (verification, error) {
	return verifyTreeWithVerifier(tree, workers, out, verifySource)
}

func verifyTreeWithVerifier(tree *filesys.VirtualFS, workers int, out string, verify func(string, []byte, *ssa.AntlrCache) sourceCheck) (verification, error) {
	var paths []string
	if err := filesys.Recursive(".", filesys.WithFileSystem(tree), filesys.WithFileStat(func(path string, info fs.FileInfo) error {
		if info != nil && !info.IsDir() {
			paths = append(paths, path)
		}
		return nil
	})); err != nil {
		return verification{}, err
	}
	return verifyPaths(paths, tree.ReadFile, workers, out, verify)
}

// verifyPrepared verifies exactly the sources the prepare stage produced.
// Walking the wrapped filesystem would also visit metadata files that are not
// Java and would report them as empty units.
func verifyPrepared(sources *ssautils.PreparedSources, fsys fi.FileSystem, workers int, out string) (verification, error) {
	var paths []string
	if err := sources.WalkEntries(func(name string, _ int64) error {
		paths = append(paths, name)
		return nil
	}); err != nil {
		return verification{}, err
	}
	return verifyPaths(paths, fsys.ReadFile, workers, out, verifySource)
}

func verifyPaths(paths []string, read func(string) ([]byte, error), workers int, out string, verify func(string, []byte, *ssa.AntlrCache) sourceCheck) (verification, error) {
	var result verification
	result.Files = len(paths)
	manifest, err := os.Create(filepath.Join(out, "sources.jsonl"))
	if err != nil {
		return result, err
	}
	defer manifest.Close()
	jobs := make(chan string)
	checks := make(chan sourceCheck)
	// FrontendRaw has no path-dependent parser state. Share completed checks
	// only for byte-identical source AND the same descriptor role. A string
	// key compares the complete bytes, not just a hash; no AST is retained.
	type sourceKey struct {
		content    string
		descriptor bool
	}
	type pendingCheck struct {
		ready chan struct{}
		check sourceCheck
	}
	var memoMu sync.Mutex
	memo := make(map[sourceKey]*pendingCheck)
	var wg sync.WaitGroup
	for i := 0; i < workers; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			builder := java2ssa.CreateBuilder().(*java2ssa.SSABuilder)
			cache := builder.GetAntlrCache()
			defer cache.Clear()
			for path := range jobs {
				readStarted := time.Now()
				src, err := read(path)
				readSeconds := time.Since(readStarted).Seconds()
				if err != nil {
					checks <- sourceCheck{Path: path, Kind: "read_error", Error: err.Error(), ReadSeconds: readSeconds}
					continue
				}
				key := sourceKey{content: string(src), descriptor: filepath.Base(path) == "package-info.java"}
				memoMu.Lock()
				pending, reused := memo[key]
				if !reused {
					pending = &pendingCheck{ready: make(chan struct{})}
					memo[key] = pending
				}
				memoMu.Unlock()
				if reused {
					<-pending.ready
				} else {
					checkStarted := time.Now()
					pending.check = verify(path, src, cache)
					pending.check.CheckSeconds = time.Since(checkStarted).Seconds()
					pending.check.SHA256 = fmt.Sprintf("%x", sha256.Sum256(src))
					// Reset the SAME worker-owned cache after releasing this AST.
					cache.ResetRuntimeCaches()
					close(pending.ready)
				}
				check := pending.check
				check.Path, check.Reused = path, reused
				check.ReadSeconds = readSeconds
				checks <- check
			}
		}()
	}
	go func() {
		for _, path := range paths {
			jobs <- path
		}
		close(jobs)
		wg.Wait()
		close(checks)
	}()
	encoder := json.NewEncoder(manifest)
	var writeErr error
	for check := range checks {
		if writeErr == nil {
			writeStarted := time.Now()
			writeErr = encoder.Encode(check)
			result.ManifestWriteSeconds += time.Since(writeStarted).Seconds()
		}
		result.Checked++
		result.ReadWorkerSeconds += check.ReadSeconds
		if check.Kind != "decompiler_refusal" && check.Kind != "read_error" {
			result.FrontendFiles++
			if !check.Reused {
				result.FrontendCalls++
			}
		}
		switch check.Kind {
		case "java", "descriptor":
			result.JavaFiles++
		case "frontend_error":
			result.FrontendFailures++
		case "decompiler_refusal":
			result.DecompilerRefusals++
		case "empty_unit":
			result.EmptyUnits++
		case "read_error":
			result.ReadFailures++
		}
		if check.Reused {
			result.ReusedChecks++
		} else {
			result.UniqueChecks++
			result.JavaWorkerSeconds += check.ParseSeconds
			result.CheckWorkerSeconds += check.CheckSeconds
		}
		if check.Error != "" {
			result.SyntaxFailures++
		}
		result.StubMethods += check.Stubs
		if check.Stubs > 0 {
			result.StubFiles++
		}
		if check.Suppressed {
			result.Suppressed++
		}
		if check.Error != "" || check.Stubs > 0 {
			result.Issues = append(result.Issues, check)
		}
		if result.Checked%1000 == 0 || result.Checked == len(paths) {
			fmt.Printf("verify %d/%d syntax_failures=%d stubs=%d\n", result.Checked, len(paths), result.SyntaxFailures, result.StubMethods)
		}
	}
	return result, writeErr
}

func run(root, out string) (int, error) {
	out, err := filepath.Abs(out)
	if err != nil {
		return 1, err
	}
	if !strings.HasPrefix(out+string(os.PathSeparator), "/mnt/data/scan-outputs/") {
		return 1, fmt.Errorf("debug output must be under /mnt/data/scan-outputs/: %s", out)
	}
	if err := os.MkdirAll(out, 0755); err != nil {
		return 1, err
	}
	// CPU samples are collected through the advertised pprof address. Keeping
	// an always-on StartCPUProfile here would prevent 5-minute HTTP snapshots.
	// Keep mutex sampling, but avoid spending most of preparation collecting
	// unique stacks (the 2008 run's profile serializer retained ~490 MiB).
	// 100 means an average of one sample per 100 contention events.
	previousMutexRate := runtime.SetMutexProfileFraction(100)
	defer runtime.SetMutexProfileFraction(previousMutexRate)
	runtime.SetBlockProfileRate(1_000_000)
	defer func() {
		for _, kind := range []string{"heap", "allocs", "goroutine", "mutex", "block"} {
			file, err := os.Create(filepath.Join(out, kind+".prof"))
			if err != nil {
				fmt.Fprintln(os.Stderr, err)
				continue
			}
			if err := pprof.Lookup(kind).WriteTo(file, 0); err != nil {
				fmt.Fprintln(os.Stderr, err)
			}
			file.Close()
		}
	}()
	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		return 1, err
	}
	server := &http.Server{ReadHeaderTimeout: 5 * time.Second}
	defer server.Close()
	go server.Serve(ln)
	fmt.Printf("pprof http://%s/debug/pprof/\n", ln.Addr())
	fmt.Printf("gomaxprocs=%d gogc=%s gomemlimit=%s target=%s\n", runtime.GOMAXPROCS(0), os.Getenv("GOGC"), os.Getenv("GOMEMLIMIT"), root)
	started := time.Now()
	result, err := ssautils.MaterializeProject(root, runtime.GOMAXPROCS(0))
	if err != nil {
		return 1, err
	}
	defer result.Sources.Close()
	prepared := time.Since(started)
	// The function producing the tree has returned: none of its wrappers,
	// archive ownership plans, parser tables or worker stacks need survive.
	runtime.GC()
	debug.FreeOSMemory()
	var beforeVerify runtime.MemStats
	runtime.ReadMemStats(&beforeVerify)
	fmt.Printf("prepared files=%d bytes=%d elapsed=%s retained_heap_alloc=%d retained_heap_inuse=%d\n", result.Files, result.Bytes, prepared, beforeVerify.HeapAlloc, beforeVerify.HeapInuse)
	verifyStarted := time.Now()
	report, err := verifyPrepared(result.Sources, result.FS, runtime.GOMAXPROCS(0), out)
	if err != nil {
		return 1, err
	}
	report.PrepareSeconds = prepared.Seconds()
	report.VerifySeconds = time.Since(verifyStarted).Seconds()
	report.SourceBytes = result.Bytes
	report.Preparation = result.Timings
	report.MaterializationErrors = result.Errors
	runtime.GC()
	debug.FreeOSMemory()
	var ms runtime.MemStats
	runtime.ReadMemStats(&ms)
	report.HeapAlloc, report.HeapInuse = ms.HeapAlloc, ms.HeapInuse
	raw, err := json.MarshalIndent(report, "", "  ")
	if err != nil {
		return 1, err
	}
	if err := os.WriteFile(filepath.Join(out, "verification.json"), append(raw, '\n'), 0644); err != nil {
		return 1, err
	}
	fmt.Printf("finished files=%d checked=%d syntax_failures=%d stub_methods=%d suppressed=%d elapsed=%s heap_alloc=%d heap_inuse=%d sources=%T\n", report.Files, report.Checked, report.SyntaxFailures, report.StubMethods, report.Suppressed, time.Since(started), report.HeapAlloc, report.HeapInuse, result.FS)
	runtime.KeepAlive(result.FS)
	if report.SyntaxFailures > 0 || report.StubMethods > 0 || report.MaterializationErrors > 0 {
		return 1, nil
	}
	return 0, nil
}

func main() {
	out := flag.String("debug", "", "absolute diagnostic output directory beneath /mnt/data/scan-outputs/")
	flag.Parse()
	if *out == "" || flag.NArg() != 1 {
		fmt.Fprintln(os.Stderr, "usage: materialize --debug <run-dir> <project-root>")
		os.Exit(2)
	}
	code, err := run(flag.Arg(0), *out)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
	}
	os.Exit(code)
}
