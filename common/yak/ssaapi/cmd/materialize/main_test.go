package main

import (
	"testing"

	"github.com/yaklang/yaklang/common/yak/java/java2ssa"
)

func TestVerificationDoesNotCountStubsOrEmptyJavaAsSuccess(t *testing.T) {
	builder := java2ssa.CreateBuilder().(*java2ssa.SSABuilder)
	cache := builder.GetAntlrCache()
	defer cache.Clear()
	for _, tt := range []struct {
		name, src  string
		error      bool
		stubs      int
		suppressed bool
	}{
		{"valid", `class A { int call() { return 1; } }`, false, 0, false},
		{"invalid cast parameter", `class A { void call((Class)(Class var1)) {} }`, true, 0, false},
		{"empty", "// not Java", true, 0, false},
		{"dump failed", "// decompile dump failed for A.class: broken", true, 0, false},
		{"stub", `class A { void call() { throw new RuntimeException("yak-decompiler: undecompilable method body"); } }`, false, 1, false},
		{"folded", "// A$1: folded into A (regenerated by javac on recompile)", false, 0, true},
		{"dropped class", "package sample;\n", true, 0, false},
	} {
		t.Run(tt.name, func(t *testing.T) {
			got := verifySource("A.java", []byte(tt.src), cache)
			cache.ResetRuntimeCaches()
			if (got.Error != "") != tt.error || got.Stubs != tt.stubs || got.Suppressed != tt.suppressed {
				t.Fatalf("verification = %+v", got)
			}
		})
	}
	got := verifySource("sample/package-info.java", []byte("@Deprecated\npackage sample;\n"), cache)
	if got.Error != "" || got.Suppressed {
		t.Fatalf("package-info = %+v", got)
	}
	cache.ResetRuntimeCaches()
}
