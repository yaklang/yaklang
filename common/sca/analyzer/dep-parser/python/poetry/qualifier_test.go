package poetry

import (
	"bytes"
	"strings"
	"testing"

	"github.com/yaklang/yaklang/common/sca/analyzer/dep-parser/types"
)

func TestParsePoetryOriginalDeclarations(t *testing.T) {
	src := `# This file is automatically @generated by Poetry and should not be changed by hand.

[[package]]
name = "app"
version = "1.0.0"
description = ""
category = "main"
optional = false
python-versions = "*"
files = []

[package.dependencies]
foo = ">=1.0"
bar = {version = ">=2.0", extras = ["toml"], markers = "python_version < \"3.11\""}
missing = "*"
empty = ""
amb = ">=1.0"
gitdep = "*"

[[package]]
name = "foo"
version = "1.2.0"
description = ""
category = "main"
optional = false
python-versions = "*"
files = []

[[package]]
name = "bar"
version = "2.0.0"
description = ""
category = "main"
optional = true
python-versions = "*"
files = []

[[package]]
name = "amb"
version = "1.0.0"
description = ""
category = "main"
optional = false
python-versions = "*"
files = []

[[package]]
name = "amb"
version = "2.0.0"
description = ""
category = "main"
optional = false
python-versions = "*"
files = []

[[package]]
name = "gitdep"
version = "0.1.0"
description = ""
category = "main"
optional = false
python-versions = "*"
files = []

[package.source]
type = "git"
url = "https://github.com/example/tool.git"
resolved_reference = "abcdef"
`
	libs, deps, err := NewParser().Parse(nil, bytes.NewReader([]byte(src)))
	if err != nil {
		t.Fatal(err)
	}
	libOf := map[string]types.Library{}
	for _, lib := range libs {
		libOf[lib.Name+"@"+lib.Version] = lib
		if strings.HasPrefix(lib.ID, "unresolved-") {
			t.Fatalf("synthetic %q", lib.ID)
		}
	}
	if libOf["foo@1.2.0"].Version != "1.2.0" {
		t.Fatal("foo missing")
	}
	if libOf["bar@2.0.0"].Scope != "optional" {
		t.Fatalf("bar optional scope %q", libOf["bar@2.0.0"].Scope)
	}
	if libOf["gitdep@0.1.0"].Source != "https://github.com/example/tool.git#abcdef" {
		t.Fatalf("git source %q", libOf["gitdep@0.1.0"].Source)
	}
	if libOf["app@1.0.0"].Locations == nil || libOf["app@1.0.0"].Locations[0].StartLine < 1 {
		t.Fatalf("location %+v", libOf["app@1.0.0"].Locations)
	}
	appID := libOf["app@1.0.0"].ID
	var qs []types.Requirement
	for _, d := range deps {
		if d.ID != appID {
			continue
		}
		qs = d.Requirements
		for _, id := range d.DependsOn {
			if strings.HasPrefix(id, "unresolved-") {
				t.Fatalf("synthetic dependsOn %q", id)
			}
		}
	}
	got := map[string]types.Requirement{}
	for _, q := range qs {
		got[q.Target] = q
	}
	if got["foo"].Constraint != ">=1.0" || got["foo"].Resolved == "" {
		t.Fatalf("foo %+v", got["foo"])
	}
	if got["foo"].Constraint == "1.2.0" {
		t.Fatal("locked version used as original expression")
	}
	if got["bar"].Constraint != ">=2.0" || got["bar"].Condition != `python_version < "3.11"; extras=[toml]` {
		t.Fatalf("bar markers/extras %+v", got["bar"])
	}
	if got["missing"].Constraint != "*" || got["missing"].Resolved != "" {
		t.Fatalf("missing %+v", got["missing"])
	}
	if got["empty"].Constraint != "" || got["empty"].Resolved != "" {
		t.Fatalf("empty %+v", got["empty"])
	}
	if got["amb"].Constraint != ">=1.0" || got["amb"].Resolved != "" {
		t.Fatalf("ambiguous uniquely resolved: %+v", got["amb"])
	}
	if got["gitdep"].Constraint != "*" || got["gitdep"].Resolved == "" {
		t.Fatalf("gitdep %+v", got["gitdep"])
	}
}
