func TestPoetryOriginalRangeMarkersExtrasSource(t *testing.T) {
	lock := `# This file is automatically @generated by Poetry and should not be changed by hand.

[[package]]
name = "app"
version = "1.0.0"
description = ""
category = "main"
optional = false
python-versions = "*"
files = []

[package.dependencies]
foo = ">=1.0"
bar = {version = ">=2.0", extras = ["toml"], markers = "python_version < \"3.11\""}
missing = "*"
amb = ">=1.0"

[[package]]
name = "foo"
version = "1.2.0"
description = ""
category = "main"
optional = false
python-versions = "*"
files = []

[[package]]
name = "bar"
version = "2.0.0"
description = ""
category = "main"
optional = true
python-versions = "*"
files = []

[[package]]
name = "amb"
version = "1.0.0"
description = ""
category = "main"
optional = false
python-versions = "*"
files = []

[[package]]
name = "amb"
version = "2.0.0"
description = ""
category = "main"
optional = false
python-versions = "*"
files = []

[[package]]
name = "gitdep"
version = "0.1.0"
description = ""
category = "main"
optional = false
python-versions = "*"
files = []

[package.source]
type = "git"
url = "https://github.com/example/tool.git"
resolved_reference = "abcdef"
`
	r, err := ScanReport(context.Background(), fstest.MapFS{"poetry.lock": {Data: []byte(lock)}}, WithSnapshotID("poetry-qual"))
	if r == nil || err != nil || !r.Complete {
		t.Fatalf("complete=%v err=%v", r != nil && r.Complete, err)
	}
	app := mustNamed(t, r, "app", "1.0.0")
	foo := mustNamed(t, r, "foo", "1.2.0")
	bar := mustNamed(t, r, "bar", "2.0.0")
	if bar.Key.Architecture != "" || len(bar.Licenses) != 0 {
		t.Fatalf("invented arch/license %+v", bar)
	}
	git := mustNamed(t, r, "gitdep", "0.1.0")
	if git.Key.Source != "https://github.com/example/tool.git#abcdef" {
		t.Fatalf("git source %q", git.Key.Source)
	}
	from := obsIDFor(t, r, app.Key.ID())
	var sawFoo, sawBar, sawMissing, sawAmb bool
	for _, q := range r.Requirements {
		if q.From != from {
			continue
		}
		switch q.Target {
		case "foo":
			sawFoo = true
			if q.Constraint != ">=1.0" || len(q.Resolved) != 1 || obsComponent(r, q.Resolved[0]) != foo.Key.ID() {
				t.Fatalf("foo %+v", q)
			}
		case "bar":
			sawBar = true
			if q.Constraint != ">=2.0" || q.Condition != `python_version < "3.11"; extras=[toml]` {
				t.Fatalf("bar %+v", q)
			}
			if len(q.Resolved) != 1 || obsComponent(r, q.Resolved[0]) != bar.Key.ID() {
				t.Fatalf("bar resolved %+v", q)
			}
		case "missing":
			sawMissing = true
			if q.Constraint != "*" || len(q.Resolved) != 0 {
				t.Fatalf("missing %+v", q)
			}
		case "amb":
			sawAmb = true
			if q.Constraint != ">=1.0" || len(q.Resolved) != 0 {
				t.Fatalf("ambiguous uniquely resolved %+v", q)
			}
		}
	}
	if !sawFoo || !sawBar || !sawMissing || !sawAmb {
		t.Fatalf("missing relations: %s", extra5149JSON(t, r.Requirements))
	}
	assertSBOMReq(t, r, from, "foo", ">=1.0", "", func() []string {
		for _, q := range r.Requirements {
			if q.From == from && q.Target == "foo" {
				return q.Resolved
			}
		}
		return nil
	}())
}

func TestPoetryFrozenFlaskOriginalRanges(t *testing.T) {
	raw, err := os.ReadFile("testdata/python_poetry/positive/poetry.lock")
	if err != nil {
		t.Fatal(err)
	}
	r, err := ScanReport(context.Background(), fstest.MapFS{"poetry.lock": {Data: raw}}, WithSnapshotID("poetry-flask"))
	if r == nil || err != nil || !r.Complete {
		t.Fatalf("complete=%v err=%v", r != nil && r.Complete, err)
	}
	flask := mustNamed(t, r, "flask", "1.1.4")
	click := mustNamed(t, r, "click", "7.1.2")
	from := obsIDFor(t, r, flask.Key.ID())
	found := false
	for _, q := range r.Requirements {
		if q.From != from || q.Target != "click" {
			continue
		}
		found = true
		if q.Constraint != ">=5.1,<8.0" {
			t.Fatalf("original flask click range lost: %+v", q)
		}
		if len(q.Resolved) != 1 || obsComponent(r, q.Resolved[0]) != click.Key.ID() {
			t.Fatalf("click resolved %+v", q)
		}
	}
	if !found {
		t.Fatalf("flask->click missing: %s", extra5149JSON(t, r.Requirements))
	}
}

func poetryLockWithFooSources(urls []string) string {
	s := `[[package]]
name = "app"
version = "1.0.0"
category = "main"
[package.dependencies]
foo = "*"
`
	for _, u := range urls {
		s += `
[[package]]
name = "foo"
version = "1.0.0"
category = "main"
[package.source]
type = "git"
url = "` + u + `"
resolved_reference = "abcdef"
`
	}
	return s
}

func TestPoetrySameVersionDifferentSources(t *testing.T) {
	orders := [][]string{
		{"https://a.example/repo.git", "https://b.example/repo.git"},
		{"https://b.example/repo.git", "https://a.example/repo.git"},
	}
	for _, urls := range orders {
		r, err := ScanReport(context.Background(), fstest.MapFS{"poetry.lock": {Data: []byte(poetryLockWithFooSources(urls))}}, WithSnapshotID("poetry-src"))
		if r == nil || err != nil || !r.Complete {
			t.Fatalf("order %v complete=%v err=%v comps=%d", urls, r != nil && r.Complete, err, len(r.Components))
		}
		mustNamed(t, r, "app", "1.0.0")
		var a, b model.Component
		for _, c := range r.Components {
			if c.Key.Name != "foo" || c.Key.Version != "1.0.0" {
				continue
			}
			switch c.Key.Source {
			case "https://a.example/repo.git#abcdef":
				a = c
			case "https://b.example/repo.git#abcdef":
				b = c
			}
		}
		if a.Key.Name == "" || b.Key.Name == "" {
			t.Fatalf("missing source identities: %+v", r.Components)
		}
		if a.Key.ID() == b.Key.ID() {
			t.Fatal("different git sources collapsed")
		}
		app := mustNamed(t, r, "app", "1.0.0")
		from := obsIDFor(t, r, app.Key.ID())
		found := false
		for _, q := range r.Requirements {
			if q.From != from || q.Target != "foo" {
				continue
			}
			found = true
			if q.Constraint != "*" {
				t.Fatalf("original * lost: %+v", q)
			}
			if len(q.Resolved) != 0 {
				t.Fatalf("ambiguous name uniquely resolved: %+v", q)
			}
		}
		if !found {
			t.Fatalf("app->foo missing: %s", extra5149JSON(t, r.Requirements))
		}
	}
}

func TestPoetrySameSourceDuplicateMerges(t *testing.T) {
	lock := poetryLockWithFooSources([]string{"https://a.example/repo.git", "https://a.example/repo.git"})
	r, err := ScanReport(context.Background(), fstest.MapFS{"poetry.lock": {Data: []byte(lock)}}, WithSnapshotID("poetry-dup"))
	if r == nil || err != nil || !r.Complete {
		t.Fatalf("complete=%v err=%v", r != nil && r.Complete, err)
	}
	n := 0
	for _, c := range r.Components {
		if c.Key.Name == "foo" && c.Key.Version == "1.0.0" && c.Key.Source == "https://a.example/repo.git#abcdef" {
			n++
		}
	}
	if n != 1 {
		t.Fatalf("same source should merge, got %d: %+v", n, r.Components)
	}
}

func TestPoetryDifferentVersionsStayDistinct(t *testing.T) {
	lock := `[[package]]
name = "app"
version = "1.0.0"
category = "main"
[package.dependencies]
foo = "*"

[[package]]
name = "foo"
version = "1.0.0"
category = "main"

[[package]]
name = "foo"
version = "2.0.0"
category = "main"
`
	r, err := ScanReport(context.Background(), fstest.MapFS{"poetry.lock": {Data: []byte(lock)}}, WithSnapshotID("poetry-vers"))
	if r == nil || err != nil || !r.Complete {
		t.Fatalf("complete=%v err=%v", r != nil && r.Complete, err)
	}
	mustNamed(t, r, "foo", "1.0.0")
	mustNamed(t, r, "foo", "2.0.0")
	app := mustNamed(t, r, "app", "1.0.0")
	from := obsIDFor(t, r, app.Key.ID())
	for _, q := range r.Requirements {
		if q.From == from && q.Target == "foo" && len(q.Resolved) != 0 {
			t.Fatalf("two versions uniquely resolved: %+v", q)
		}
	}
}
