// Command generate creates deterministic gzip sidecars and explicit go:embed
// directives. Originals stay editable in the repository but are not embedded twice.
package main

import (
	"bytes"
	"compress/gzip"
	"flag"
	"fmt"
	"go/build/constraint"
	"go/format"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const suffix = ".embed.gz"

func main() {
	pkg := flag.String("package", "", "Go package name")
	variable := flag.String("var", "FS", "public filesystem variable")
	output := flag.String("output", "resources_embed.go", "generated Go file")
	buildTag := flag.String("build-tag", "", "optional Go build constraint")
	check := flag.Bool("check", false, "verify generated files without writing")
	flag.Parse()
	if *pkg == "" || flag.NArg() == 0 {
		flag.Usage()
		os.Exit(2)
	}
	if err := generate(*pkg, *variable, *output, flag.Args(), *check, *buildTag); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(pkg, variable, output string, roots []string, check bool, buildTag string) error {
	if buildTag != "" {
		if _, err := constraint.Parse("//go:build " + buildTag); err != nil {
			return err
		}
	}
	files := map[string]bool{}
	sidecars := map[string]bool{}
	for _, root := range roots {
		err := filepath.WalkDir(root, func(name string, entry fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			base := entry.Name()
			if strings.HasPrefix(base, ".") || strings.HasPrefix(base, "_") {
				if entry.IsDir() {
					return filepath.SkipDir
				}
				return nil
			}
			if entry.IsDir() {
				return nil
			}
			if entry.Type()&fs.ModeSymlink != 0 {
				return fmt.Errorf("symlink resource: %s", name)
			}
			name = filepath.ToSlash(name)
			if strings.HasSuffix(name, suffix) {
				sidecars[name] = true
				return nil
			}
			files[name] = true
			return nil
		})
		if err != nil {
			return err
		}
	}
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	var directives strings.Builder
	var before, after, compressed int
	for _, name := range names {
		raw, err := os.ReadFile(name)
		if err != nil {
			return err
		}
		if uint64(len(raw)) >= 1<<32 {
			return fmt.Errorf("resource exceeds gzip size limit: %s", name)
		}
		before += len(raw)
		storage := name
		data := raw
		// Existing archives are passed through unchanged, including encrypted tar.gz.
		ext := strings.ToLower(filepath.Ext(name))
		if ext != ".gz" && ext != ".gzip" && ext != ".zip" && ext != ".zst" && len(raw) >= 512 {
			var buf bytes.Buffer
			w, err := gzip.NewWriterLevel(&buf, gzip.BestCompression)
			if err != nil {
				return err
			}
			if _, err = w.Write(raw); err != nil {
				return err
			}
			if err = w.Close(); err != nil {
				return err
			}
			if len(raw)-buf.Len() >= 256 && buf.Len()*5 <= len(raw)*4 {
				storage = name + suffix
				data = buf.Bytes()
				compressed++
				if err := update(storage, data, check); err != nil {
					return err
				}
				delete(sidecars, storage)
			}
		}
		after += len(data)
		fmt.Fprintf(&directives, "//go:embed %s\n", strconv.Quote(storage))
	}
	for name := range sidecars {
		if check {
			return fmt.Errorf("stale generated resource: %s", name)
		}
		if err := os.Remove(name); err != nil {
			return err
		}
	}
	code := fmt.Sprintf("// Code generated by embedfs/generate; DO NOT EDIT.\n\npackage %s\n\nimport (\n\"embed\"\n\n\"github.com/yaklang/yaklang/common/utils/embedfs\"\n)\n\n%svar %sStorage embed.FS\n\nvar %s = embedfs.New(%sStorage)\n", pkg, directives.String(), variable, variable, variable)
	if buildTag != "" {
		code = "//go:build " + buildTag + "\n\n" + code
	}
	formatted, err := format.Source([]byte(code))
	if err != nil {
		return err
	}
	if err := update(output, formatted, check); err != nil {
		return err
	}
	fmt.Printf("%s: %d files, %d compressed, %d -> %d bytes (saved %d)\n", output, len(names), compressed, before, after, before-after)
	return nil
}

func update(name string, data []byte, check bool) error {
	old, err := os.ReadFile(name)
	if err == nil && bytes.Equal(old, data) {
		return nil
	}
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	if check {
		return fmt.Errorf("regenerate embedded resource: %s", name)
	}
	return os.WriteFile(name, data, 0644)
}
