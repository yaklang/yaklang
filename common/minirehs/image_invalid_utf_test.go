func TestInvalidUTFRequiredLiterals(t *testing.T) {
	for _, expr := range []string{`\x{FFFD}foo`, `foo\x{FFFD}`, `\x{FFFD}foo(?=!)`, `foo\x{FFFD}(?=!)`,
		`\x{FFFD}`, `(?:\x{FFFD}|foo)`, `(?i)\x{FFFD}SK`, `(?i)K\x{FFFD}foo`} {
		for _, backend := range []BackendKind{BackendEngine, BackendStdlib, BackendMVS} {
			for _, locate := range []bool{false, true} {
				t.Run(fmt.Sprintf("%s/%s/loc=%v", expr, backend, locate), func(t *testing.T) {
					patterns := []Pattern{{ID: 17, Expr: expr}}
					db, err := Compile(patterns, WithBackend(backend), WithReportLocation(locate), WithLogger(silentLogger{}))
					if err != nil {
						t.Fatal(err)
					}
					defer db.Close()
					current := []Database{db}
					if backend == BackendMVS {
						image, err := db.MarshalImage()
						if err != nil {
							t.Fatal(err)
						}
						loaded, err := LoadImage(image)
						if err != nil {
							t.Fatal(err)
						}
						defer loaded.Close()
						current = append(current, loaded)
					}
					for _, candidate := range current {
						for _, data := range [][]byte{nil, []byte("�foo! foo�! �SK K�foo"),
							{'\xff', 'f', 'o', 'o', '!'}, {'f', 'o', 'o', '\xff', '!'},
							{0xc0, 0xaf, 'f', 'o', 'o', '!'}, {0xe2, 0x82, 'f', 'o', 'o', '!'},
							{'\xff', 'S', 'K'}, {'K', '\xff', 'f', 'o', 'o'}} {
							for _, stop := range []int{0, 1, 2} {
								got := programScan(t, candidate, data, stop)
								want := programOracle(patterns, data, backend, locate, stop)
								if err := programCompare(got, want, true); err != nil {
									t.Fatalf("input=%q stop=%d: %s", data, stop, err)
								}
							}
						}
					}
				})
			}
		}
	}
}

func TestLegacyImageInvalidUTF(t *testing.T) {
	for _, locate := range []bool{false, true} {
		name := map[bool]string{false: "exist", true: "located"}[locate]
		image, err := os.ReadFile("testdata/compile-image-v4-invalid-utf-" + name + ".rehs")
		if err != nil {
			t.Fatal(err)
		}
		if binary.LittleEndian.Uint32(image[4:]) != 4 {
			t.Fatal("fixture must have been generated by the actual v4 compiler")
		}
		compileCalls := 0
		func() {
			imageParseHook = func() { compileCalls++ }
			imageNFAHook = func() { compileCalls++ }
			imageCompileHook = func() { compileCalls++ }
			defer func() { imageParseHook, imageNFAHook, imageCompileHook = nil, nil, nil }()
			db, err := LoadImage(image)
			if err != nil {
				t.Fatal(err)
			}
			defer db.Close()
			if compileCalls != 0 || !db.(*database).imageMVS().legacyInvalidUTF {
				t.Fatal("legacy load compiled or lost invalid-UTF compatibility")
			}
			exported, err := db.MarshalImage()
			if err != nil || !bytes.Equal(exported, image) {
				t.Fatal("legacy byte-identical re-export changed", err)
			}
			for _, data := range [][]byte{{'\xff', 'f', 'o', 'o', '!'}, {'b', 'a', 'r', '\xff'},
				{0xe2, 0x82, 'f', 'o', 'o', '!'}, {'\xff', 'a', 'a', 'a', ' ', 'b', 'a', 'r', '\xff'}} {
				var want programObservation
				for _, p := range programInvalidUTFPatterns() {
					// ID 34 is the deliberate nullable RE2 fallback exception.
					part := programOracle([]Pattern{p}, data, BackendMVS, locate, 0, p.ID == 34)
					want.Callbacks = append(want.Callbacks, part.Callbacks...)
					if part.Error != nil {
						t.Fatal(part.Error)
					}
				}
				want.Completed = true
				if err := programCompare(programScan(t, db, data, 0), want, false); err != nil {
					t.Fatalf("legacy %s data=%q: %s", name, data, err)
				}
			}
		}()
	}
}

func TestLegacyInvalidUTFCacheRefresh(t *testing.T) {
	legacy, err := os.ReadFile("testdata/compile-image-v4-invalid-utf-exist.rehs")
	if err != nil {
		t.Fatal(err)
	}
	cache := filepath.Join(t.TempDir(), "rules.rehs")
	if err := os.WriteFile(cache, legacy, 0600); err != nil {
		t.Fatal(err)
	}
	compiles := 0
	imageCompileHook = func() { compiles++ }
	defer func() { imageCompileHook = nil }()
	for i := 0; i < 2; i++ {
		db, err := LoadOrCompile(cache, programInvalidUTFPatterns(), WithBackend(BackendMVS), WithReportLocation(false), WithLogger(silentLogger{}))
		if err != nil {
			t.Fatal(err)
		}
		if db.(*database).imageMVS().legacyInvalidUTF {
			t.Fatal("obsolete plan reused from cache")
		}
		db.Close()
	}
	if compiles != 1 {
		t.Fatalf("cache compiled %d times, want one refresh then one hit", compiles)
	}
	current, err := os.ReadFile(cache)
	if err != nil || binary.LittleEndian.Uint32(current[4:]) != imageVersion {
		t.Fatal("cache was not refreshed to the current semantic version", err)
	}
}

func FuzzInvalidUTFRequiredLiterals(f *testing.F) {
	type candidate struct {
		db       Database
		patterns []Pattern
		backend  BackendKind
		locate   bool
	}
	var candidates []candidate
	for _, expr := range []string{`\x{FFFD}foo`, `foo\x{FFFD}(?=!)`, `(?i)K\x{FFFD}foo`} {
		for _, backend := range []BackendKind{BackendEngine, BackendMVS} {
			for _, locate := range []bool{false, true} {
				patterns := []Pattern{{ID: 17, Expr: expr}}
				db, err := Compile(patterns, WithBackend(backend), WithReportLocation(locate), WithLogger(silentLogger{}))
				if err != nil {
					f.Fatal(err)
				}
				f.Cleanup(func() { db.Close() })
				candidates = append(candidates, candidate{db, patterns, backend, locate})
			}
		}
	}
	for _, data := range [][]byte{nil, []byte("�foo! foo�! K�foo"), {'\xff', 'f', 'o', 'o', '!'},
		{'f', 'o', 'o', 0xe2, 0x82, '!'}, {'K', '\xff', 'f', 'o', 'o'}} {
		f.Add(data)
	}
	f.Fuzz(func(t *testing.T, data []byte) {
		for _, c := range candidates {
			got := programScan(t, c.db, data, 0)
			want := programOracle(c.patterns, data, c.backend, c.locate, 0)
			if err := programCompare(got, want, true); err != nil {
				t.Fatalf("expr=%q backend=%s locate=%v input=%x: %s", c.patterns[0].Expr, c.backend, c.locate, data, err)
			}
		}
	})
}
